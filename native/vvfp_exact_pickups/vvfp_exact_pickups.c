/* VVFP Exact Pickups -- Fix Vanilla Bugs (The Secret City, The Tree of Life, New Believers): with the VV1
   Mushroom/Collectible Duplication Cheat, each child dropped on a mushroom or collectible takes exactly the item it
   was dropped on, and nothing else, off the island.

   The owner (2026-11-27): "no other mushroom or collectible may ever vanish, including a same-kind one within 30 px
   of the dropped one".

   THE STOCK GAMES.  The collectible manager (VV3 vtable 0x482938, VV4 0x48C4D8, VV5 0x4974F8; its slots from
   +4, 0x1C bytes each: active byte, id +4, end time +8, x +0xC, y +0x10, reserver +0x14) answers a drop through vf2
   (VV3 0x42DDB0, VV4 0x413A20, VV5 0x413E40): the FIRST slot, in slot order, that is active, not reserved (the
   reservation test is the `jne` at +0x1F that the Duplication Cheat turns into two nops) and within 30 pixels
   (distance squared below 0x384) is the one; its id goes back to the drop, which starts the pick action.  The pick
   plays its animation where the child stands and then puts the item in the child's hands; the item listeners call
   vf0 (VV3 0x42D5E0, VV4 0x4139A0, VV5 0x413DC0), which removes the active item of that id NEAREST the child
   (out to 1,000 pixels in the base game, 30 with Fix Vanilla Bugs' own byte fix) and returns 1.  vf0 never knows
   which item the child was dropped on: with the cheat, every child after the first takes the next nearest item of
   the same kind -- one 10 pixels from the first as readily as one across the island.

   WHAT THIS COMPANION DOES.  It replaces the manager's two vtable entries (data, in the read-only data section; no
   byte of the game's code is written):
     vf2 -> ep_hit: works out, before the game's own vf2 runs, the slot the game will choose -- the same test in the
            same order -- and runs the game's vf2.  When the game accepts the drop with that slot's id, the child
            (its record address) is remembered with that slot and the item's id and place; any other answer forgets
            the child.
     vf0 -> ep_pick: a child remembered with the id it now carries is forgotten, and the item it was dropped on is
            removed through the game's own routine (VV3 0x42D520, VV4 0x4138C0, VV5 0x413CE0) when that slot still
            holds that item (active, the same id and place); when it is already gone, nothing is removed.  It
            returns 1, as vf0 always does, so the child keeps its copy, its pay and its count.  A child not
            remembered (an item put in its hands some other way) goes to the game's own vf0, unchanged.

   ALL OR NONE.  Installed only in the three games, only when the Duplication Cheat is in (the two nops; without it
   only one child can be dropped on an item and nothing here would change anything), and only when both vtable
   entries hold the stock routines and the three routines hold their stock bytes (vf0 with either its stock reach
   or Fix Vanilla Bugs' 0x384).  Otherwise nothing is changed.  Started by "VVFP Window Restore.dll" (the Fix
   Vanilla Bugs rows ship both), before WinMain, on the game's own thread.  No file, no text, no save data, no
   debug output.  What it remembers lives only in memory: at most one entry per child, replaced by the child's next
   drop. */
#include <windows.h>

