/* "Story / Cheat Upgrades cost Tech Points" (the owner, 2026-10-06): set by
   the Origins companion from the patcher's startup flag before the install,
   so the zero prices are never written -- the Origins menus show and charge
   their own prices -- and Pick Island Event, Custom Island Event and Pick
   Gong of Wonder Outcome each cost what the Island Event upgrade costs. */
#define STORY_EVENT_PRICE 30000         /* the Island Event upgrade, all five games */
static int charges[6];

/* The detour `index` of this game: its pick sites, then the custom
   event's own. */
static int game_detour_count(const story_game *g) {
    return g->detour_count + g->more_detour_count;
}

static const story_detour *game_detour(const story_game *g, int index) {
    return index < g->detour_count ? &g->detours[index] : &g->more_detours[index - g->detour_count];
}

/* A write failed part-way: put the stock bytes back at the first `writes`
   price sites and the first `detours` detour sites, which were written, so
   a game reported inactive has none of the feature live. */
static void install_undo(const story_game *g, int writes, int detours) {
    int i;
    for (i = 0; i < detours; ++i) {
        const story_detour *d = game_detour(g, i);
        mem_write(d->va, d->expect, d->length);
    }
    for (i = 0; i < writes; ++i) {
        mem_write(g->writes[i].va, g->writes[i].expect, g->writes[i].length);
    }
}

/* Verify every site of this game, then write every one -- or write nothing. */
static int install(int game) {
    const story_game *g = &GAMES[game];
    unsigned char bytes[16];
    int i;
    for (i = 0; i < g->write_count; ++i) {
        if (!mem_matches(g->writes[i].va, g->writes[i].expect, g->writes[i].length)) {
            return 0;
        }
    }
    for (i = 0; i < game_detour_count(g); ++i) {
        const story_detour *d = game_detour(g, i);
        if (d->length > (int)sizeof bytes || !mem_matches(d->va, d->expect, d->length)) {
            return 0;
        }
    }
    if (!oc_verify(game)) {
        return 0;
    }
    for (i = 0; i < g->write_count && !charges[game]; ++i) {
        if (!mem_write(g->writes[i].va, g->writes[i].replace, g->writes[i].length)) {
            install_undo(g, i, 0);
            return 0;
        }
    }
    for (i = 0; i < game_detour_count(g); ++i) {
        const story_detour *d = game_detour(g, i);
        detour_bytes(d, bytes);
        if (!mem_write(d->va, bytes, d->length)) {
            install_undo(g, charges[game] ? 0 : g->write_count, i);
            return 0;
        }
    }
    if (!oc_install(game)) {
        install_undo(g, charges[game] ? 0 : g->write_count, game_detour_count(g));
        return 0;
    }
    return 1;
}

/* "Story / Cheat Upgrades cost Tech Points" for `game`: called by the
   Origins companion before the install when the patcher's startup flag says
   so.  Ignored once the install has run (its prices are what they are). */
__declspec(dllexport) void __stdcall VvfpStoryCharge(int game) {
    if (game >= 1 && game <= 5 && install_state[game] == 0) {
        charges[game] = 1;
    }
}

/* The install alone, once: every site verified, then written; nothing
   else.  Called at game start by the Origins companion's VvfpStartup (from
   "VVFP Startup.dll", at the executable's call of WinMain), before any
   village exists, so the detours are in place for the first load-time
   catch-up.  Idempotent.  Returns whether they are in place. */
__declspec(dllexport) int __stdcall VvfpStoryArm(int game) {
    if (game < 1 || game > 5) {
        return 0;
    }
    if (install_state[game] == 0) {
        install_state[game] = install(game) ? 1 : -1;
        if (install_state[game] == 1 && game == 2) {
            /* Restore Missing Island Events' lore pages, when that row is ticked. */
            vv2_install_page_roll();
        }
    }
    return install_state[game] == 1;
}

/* Called by the Origins companion of `game` (1-5) from its own per-frame or
   menu path, outside DllMain: the install (when game start has not made it)
   and the custom titles' tick.  Returns whether the free prices and the
   Pick Island Event detour are in place. */
__declspec(dllexport) int __stdcall VvfpStoryInstall(int game) {
    static DWORD last_tick;
    DWORD now;
    if (!VvfpStoryArm(game)) {
        return 0;
    }
    /* The custom titles' tick: bind to the save slot, notice a Start Over,
       forget the titles of villagers who are gone. */
    now = GetTickCount();
    if (now - last_tick >= TICK_MS) {
        last_tick = now;
        titles_tick(game);
    }
    return 1;
}

