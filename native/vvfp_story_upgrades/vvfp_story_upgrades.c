static int mem_readable(unsigned int va, int length) {
    MEMORY_BASIC_INFORMATION info;
    const void *at = (const void *)(uintptr_t)va;
    if (VirtualQuery(at, &info, sizeof(info)) != sizeof(info) || info.State != MEM_COMMIT
        || (info.Protect & (PAGE_NOACCESS | PAGE_GUARD)) != 0) {
        return 0;
    }
    return (uintptr_t)at + (unsigned int)length
           <= (uintptr_t)info.BaseAddress + info.RegionSize;
}

static int mem_matches(unsigned int va, const unsigned char *bytes, int length) {
    if (!mem_readable(va, length)) {
        return 0;
    }
    return memcmp((const void *)(uintptr_t)va, bytes, (size_t)length) == 0;
}

#ifdef VVFP_TEST
/* TEST build only: the write that fails (0 = the first), -1 = none. */
static int test_fail_write = -1;
#endif

static int mem_write(unsigned int va, const unsigned char *bytes, int length) {
    DWORD old;
    void *at = (void *)(uintptr_t)va;
#ifdef VVFP_TEST
    if (test_fail_write >= 0 && test_fail_write-- == 0) {
        return 0;
    }
#endif
    if (!VirtualProtect(at, (SIZE_T)length, PAGE_EXECUTE_READWRITE, &old)) {
        return 0;
    }
    memcpy(at, bytes, (size_t)length);
    VirtualProtect(at, (SIZE_T)length, old, &old);
    FlushInstructionCache(GetCurrentProcess(), at, (SIZE_T)length);
    return 1;
}

static unsigned int read_u32(unsigned int va) {
    return *(volatile unsigned int *)(uintptr_t)va;
}

/* The bytes a detour writes at its site: a jmp (or, for a call site, a call)
   to the stub, padded with nops. */
static void detour_bytes(const story_detour *d, unsigned char *out) {
    unsigned int rel = (unsigned int)((uintptr_t)d->stub - ((uintptr_t)d->va + 5));
    int i;
    out[0] = d->is_call ? 0xE8 : 0xE9;
    memcpy(out + 1, &rel, 4);
    for (i = 5; i < d->length; ++i) {
        out[i] = 0x90;
    }
}

