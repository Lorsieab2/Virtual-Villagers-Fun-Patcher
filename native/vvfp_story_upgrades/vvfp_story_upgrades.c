static const ce_adapter *ce_adapter_for(int game) {
    switch (game) {
    case 1: return &C1_ADAPTER;
    case 2: return &C2_ADAPTER;
    case 3: return c3_adapter();
    case 4: return c4_adapter();
    case 5: return c5_adapter();
    default: return NULL;
    }
}

static int story_record_count(int game) {
    const ce_adapter *a = ce_adapter_for(game);
    return a != NULL ? a->record_count : 0;
}

static unsigned char *story_record(int game, int index) {
    const ce_adapter *a = ce_adapter_for(game);
    return a != NULL ? a->record(index) : NULL;
}

static int story_record_index(int game, const unsigned char *record) {
    const ce_adapter *a = ce_adapter_for(game);
    int i;
    if (a == NULL || record == NULL) {
        return -1;
    }
    for (i = 0; i < a->record_count; ++i) {
        if (a->record(i) == record) {
            return i;
        }
    }
    return -1;
}

/* A villager is still here: living, or a skeleton not yet buried or
   crumbled away (a revive can bring them back, so their custom title stays
   until the record is freed or holds someone else). */
static int story_record_present(int game, const unsigned char *record) {
    const ce_adapter *a = ce_adapter_for(game);
    return a != NULL && record != NULL
        && (a->listed(record) || (a->skeleton != NULL && a->skeleton(record)));
}

static unsigned int story_title_identity(int game, const unsigned char *record) {
    const ce_adapter *a = ce_adapter_for(game);
    return a != NULL ? vv_title_identity(record, a->off_name, (unsigned int)a->name_bytes, a->off_likes,
                                         a->off_dislikes, (unsigned int)a->pref_slots) : 0;
}

/* What a rename leaves of the title identity: the sex, likes and dislikes
   (story_titles.inc tells a rename from a new occupant by it).  Never 0. */
static unsigned int story_title_stable(int game, const unsigned char *record) {
    const ce_adapter *a = ce_adapter_for(game);
    unsigned int h;
    if (a == NULL) {
        return 0;
    }
    h = vv_title_identity(record, a->off_name, 0u, a->off_likes, a->off_dislikes, (unsigned int)a->pref_slots);
    h = (h ^ (unsigned int)*(const int *)(record + a->off_sex)) * 16777619u;
    return h ? h : 1u;
}

