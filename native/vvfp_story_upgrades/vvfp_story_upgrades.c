/* ---- Making the island event due ------------------------------------------ */

/* Each game: is an island event already on its way (the Island Event row's
   own lock), and make one due exactly as the Origins Island Event purchase
   does.  Returns 1 on success. */
static int vv3_island_pending(void) {
    return *(volatile unsigned char *)(uintptr_t)VV3_ISLAND_FLAG != 0;
}

static int vv3_arm(void) {
    void *manager = *(void **)(uintptr_t)VV3_MANAGER_GLOBAL;
    void (__fastcall *queue_arm_island)(void *, void *) =
        (void (__fastcall *)(void *, void *))(uintptr_t)VV3_QUEUE_ARM_ISLAND;
    if (manager == NULL) {
        return 0;
    }
    queue_arm_island(manager, NULL);   /* the Island Event purchase's own helper */
    return 1;
}

static int vv4_island_pending(void) {
    unsigned char *world = *(unsigned char **)(uintptr_t)VV4_WORLD_GLOBAL;
    unsigned int countdown;
    if (world == NULL) {
        return 1;
    }
    countdown = *(unsigned int *)(world + VV4_COUNTDOWN);
    if (*(volatile unsigned char *)(uintptr_t)VV4_ISLAND_TOKEN != 0
        && (countdown == read_u32(VV4_ISLAND_STAMP)
            || *(volatile unsigned char *)(uintptr_t)VV4_BARREL_ARMED != 0)) {
        return 1;
    }
    if (countdown == 0) {
        return 1;
    }
    return countdown - (unsigned int)((clock_fn)(uintptr_t)VV4_CLOCK)(world, NULL) <= 5u;
}

static int vv4_arm(void) {
    unsigned char *world = *(unsigned char **)(uintptr_t)VV4_WORLD_GLOBAL;
    unsigned int due;
    if (world == NULL) {
        return 0;
    }
    due = (unsigned int)((clock_fn)(uintptr_t)VV4_CLOCK)(world, NULL) + 5u;
    *(unsigned int *)(world + VV4_COUNTDOWN) = due;
    *(volatile unsigned char *)(uintptr_t)VV4_ISLAND_TOKEN = 1;
    *(volatile unsigned int *)(uintptr_t)VV4_ISLAND_STAMP = due;
    return 1;
}

static int vv5_island_pending(void) {
    return (read_u32(VV5_PURCHASE_FLAGS) & 0x3Cu) != 0;
}

static int vv5_arm(void) {
    unsigned char *world = *(unsigned char **)(uintptr_t)VV5_WORLD_GLOBAL;
    if (world == NULL) {
        return 0;
    }
    *(unsigned int *)(world + VV5_COUNTDOWN) = 0;
    *(volatile unsigned int *)(uintptr_t)VV5_PURCHASE_FLAGS |= 0x10u;
    return 1;
}

/* Whether the game's own condition for an event holds right now.  VV3-VV5:
   the event object's own condition, through the game's own event table
   (built by the game's own getter if no event has run yet this session). */
static int table_event_possible(unsigned int table, getter_fn getter, int slot) {
    void *object = *(void **)(uintptr_t)(table + 4u * (unsigned int)slot);
    if (object == NULL) {
        getter();
        object = *(void **)(uintptr_t)(table + 4u * (unsigned int)slot);
    }
    return object != NULL && can_fire_with_retries(object);
}

static int vv3_possible(const story_event *e) {
    return table_event_possible(VV3_EVENT_TABLE, (getter_fn)(uintptr_t)VV3_EVENT_GETTER, e->slot);
}

static int vv4_possible(const story_event *e) {
    return table_event_possible(VV4_EVENT_TABLE, (getter_fn)(uintptr_t)VV4_EVENT_GETTER, e->slot);
}

static int vv5_possible(const story_event *e) {
    return table_event_possible(VV5_EVENT_TABLE, (getter_fn)(uintptr_t)VV5_EVENT_GETTER, e->slot);
}

