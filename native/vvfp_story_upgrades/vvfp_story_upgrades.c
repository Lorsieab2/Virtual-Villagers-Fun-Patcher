static int story_pick_island_event(int game, HWND owner) {
    const story_game *g;
    const story_event *event;
    const oc_settings *settings;
    const char *warning;
    char label[160];
    char summary[1200];
    char message[1800];
    int chosen;
    int possible_now;
    if (!story_installed(game)) {
        return 0;
    }
    g = &GAMES[game];
    drop_lapsed_pick();
    ce_drop_lapsed();
    if (pick_slot >= 0 || ce_armed || g->island_pending()) {
        /* New Believers' Island Event and Barrel of Babies share one queue
           (either blocks both purchases); the pick shares it too. */
        MessageBoxA(owner,
                    game == 5
                        ? "An island event or a barrel of babies is already queued "
                          "and on its way.\n\nIt arrives shortly. Close this screen "
                          "and wait for it to arrive."
                        : "An island event is already queued and on its way.\n\n"
                          "It arrives shortly. Close this screen and wait for it to arrive.",
                    "Not right now", MB_OK | MB_ICONINFORMATION | MB_TOPMOST | MB_SETFOREGROUND);
        return 0;
    }
    if (last_failed_event != NULL) {
        label_of(last_failed_event, label, sizeof label);
        if (last_failed_lapsed) {
            wsprintfA(message,
                      "The last island event you picked, %s, did not happen within "
                      "ten minutes, so it was cancelled.", label);
        } else {
            wsprintfA(message,
                      "The last island event you picked, %s, could not happen when it "
                      "was due (it needs %s), so the island event the game chose "
                      "happened instead.",
                      label, last_failed_event->requires);
        }
        MessageBoxA(owner, message, "Pick Island Event",
                    MB_OK | MB_ICONINFORMATION | MB_TOPMOST | MB_SETFOREGROUND);
        last_failed_event = NULL;
    }
    chosen = chooser_run(game, g, owner);
    if (chosen < 0) {
        return 0;
    }
    event = &g->events[chosen];
    settings = &chooser.settings[chosen];
    label_of(event, label, sizeof label);
    chooser_summary(chosen, summary, sizeof summary);
    wsprintfA(message,
              "Do you want to buy Pick Island Event (%s) for %s tech points?%s%s\r\n\r\n"
              "Press OK to confirm, or Cancel.", label, story_price_text(game),
              summary[0] ? "\r\n" : "", summary);
    if (MessageBoxA(owner, message, "Origins Upgrades",
                    MB_OKCANCEL | MB_ICONQUESTION | MB_TOPMOST | MB_SETFOREGROUND) != IDOK) {
        return 0;
    }
    warning = chooser_warning(chosen);
    if (warning != NULL
        && MessageBoxA(owner, warning, "Pick Island Event",
                       MB_OKCANCEL | MB_ICONWARNING | MB_DEFBUTTON2 | MB_TOPMOST | MB_SETFOREGROUND)
               != IDOK) {
        return 0;
    }
    /* The village may have moved on while the boxes were open. */
    possible_now = g->possible(event) || (settings->unlocked && oc_unlock_possible(game, event));
    if (ce_armed || g->island_pending() || !possible_now || !arm_pick(game, event)) {
        MessageBoxA(owner, "That island event can not happen right now. No tech points have been deducted.",
                    "Origins Upgrades", MB_OK | MB_ICONINFORMATION | MB_TOPMOST | MB_SETFOREGROUND);
        return 0;
    }
    oc_arm(game, event->slot, settings);
    wsprintfA(message, "%s is on its way.", label);
    MessageBoxA(owner, message, "Origins Upgrades",
                MB_OK | MB_ICONINFORMATION | MB_TOPMOST | MB_SETFOREGROUND);
    return 1;
}

