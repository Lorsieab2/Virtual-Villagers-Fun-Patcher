/* The filter stops for the session: SDL draws (its texture is current). */
static void sp_fail(void) {
    g_failed = 1;
    InterlockedExchange(&g_active, 0);
    sp_free_device();
}

static int sp_target(int w, int h, D3DFORMAT format, IDirect3DTexture9 **texture) {
    return SUCCEEDED(IDirect3DDevice9_CreateTexture((IDirect3DDevice9 *)g_dev, w, h, 1, D3DUSAGE_RENDERTARGET, format,
                                                    D3DPOOL_DEFAULT, texture, NULL));
}

static int sp_make_device(int cw, int ch) {
    IDirect3DDevice9 *dev;
    int i;
    if (FAILED(g_create9ex(D3D_SDK_VERSION, &g_d3d))) {
        return 0;
    }
    memset(&g_pp, 0, sizeof g_pp);
    g_pp.Windowed = TRUE;
    g_pp.SwapEffect = D3DSWAPEFFECT_DISCARD;
    g_pp.BackBufferFormat = D3DFMT_X8R8G8B8;
    g_pp.BackBufferWidth = cw;
    g_pp.BackBufferHeight = ch;
    g_pp.BackBufferCount = 1;
    g_pp.hDeviceWindow = g_hwnd;
    g_pp.PresentationInterval = D3DPRESENT_INTERVAL_IMMEDIATE;
    /* FPU_PRESERVE: the game's floating point keeps its precision, as SDL's own device does. */
    if (FAILED(IDirect3D9Ex_CreateDeviceEx(g_d3d, D3DADAPTER_DEFAULT, D3DDEVTYPE_HAL, g_hwnd,
                                           D3DCREATE_HARDWARE_VERTEXPROCESSING | D3DCREATE_FPU_PRESERVE, &g_pp, NULL,
                                           &g_dev))) {
        return 0;
    }
    dev = (IDirect3DDevice9 *)g_dev;
    if (FAILED(IDirect3DDevice9_CreateVertexShader(dev, (const DWORD *)g_sp_vs_quad, &g_vs)) ||
        FAILED(IDirect3DDevice9_CreatePixelShader(dev, (const DWORD *)g_sp_ed_step1, &g_step1)) ||
        FAILED(IDirect3DDevice9_CreatePixelShader(dev, (const DWORD *)g_sp_ed_step2, &g_step2)) ||
        FAILED(IDirect3DDevice9_CreatePixelShader(dev, (const DWORD *)g_sp_fit_rows, &g_rows)) ||
        FAILED(IDirect3DDevice9_CreatePixelShader(dev, (const DWORD *)g_sp_fit_columns, &g_columns))) {
        return 0;
    }
    if (FAILED(IDirect3DDevice9_CreateTexture(dev, g_frame_w, g_frame_h, 1, D3DUSAGE_DYNAMIC, D3DFMT_A8R8G8B8,
                                              D3DPOOL_DEFAULT, &g_frame, NULL)) ||
        !sp_target(2 * g_frame_w, 2 * g_frame_h, D3DFMT_A8R8G8B8, &g_lattice2) ||
        !sp_target(2 * g_frame_w, 2 * g_frame_h, D3DFMT_A8R8G8B8, &g_doubled2) ||
        !sp_target(4 * g_frame_w, 4 * g_frame_h, D3DFMT_A8R8G8B8, &g_lattice4) ||
        !sp_target(4 * g_frame_w, 4 * g_frame_h, D3DFMT_A8R8G8B8, &g_doubled4)) {
        return 0;
    }
    for (i = 0; i < SP_QUERIES; ++i) {
        /* the step-down's timing: optional (without it there is no step-down) */
        if (FAILED(IDirect3DDevice9_CreateQuery(dev, D3DQUERYTYPE_TIMESTAMP, &g_q_begin[i])) ||
            FAILED(IDirect3DDevice9_CreateQuery(dev, D3DQUERYTYPE_TIMESTAMP, &g_q_end[i])) ||
            FAILED(IDirect3DDevice9_CreateQuery(dev, D3DQUERYTYPE_TIMESTAMPDISJOINT, &g_q_disjoint[i])) ||
            FAILED(IDirect3DDevice9_CreateQuery(dev, D3DQUERYTYPE_TIMESTAMPFREQ, &g_q_freq[i]))) {
            SP_RELEASE(g_q_begin[i]);
            SP_RELEASE(g_q_end[i]);
            SP_RELEASE(g_q_disjoint[i]);
            SP_RELEASE(g_q_freq[i]);
        }
    }
    return 1;
}

/* The rows picture (window width x the prescaled height), 16-bit float: made again when either changes. */
static int sp_mid(int cw, int bh) {
    if (g_mid != NULL && g_mid_w == cw && g_mid_h == bh) {
        return 1;
    }
    SP_RELEASE(g_mid);
    g_mid_w = cw;
    g_mid_h = bh;
    return sp_target(cw, bh, D3DFMT_A16B16G16R16F, &g_mid);
}

static void sp_pass(IDirect3DPixelShader9 *ps, IDirect3DTexture9 *from, int from_w, int from_h, IDirect3DSurface9 *to) {
    static const float quad[4][4] = {{-2, 2, 0.5f, 1}, {2, 2, 0.5f, 1}, {-2, -2, 0.5f, 1}, {2, -2, 0.5f, 1}};
    IDirect3DDevice9 *dev = (IDirect3DDevice9 *)g_dev;
    float size[4];
    size[0] = (float)from_w;
    size[1] = (float)from_h;
    size[2] = 1.0f / from_w;
    size[3] = 1.0f / from_h;
    IDirect3DDevice9_SetRenderTarget(dev, 0, to);
    IDirect3DDevice9_SetPixelShader(dev, ps);
    IDirect3DDevice9_SetTexture(dev, 0, (IDirect3DBaseTexture9 *)from);
    IDirect3DDevice9_SetPixelShaderConstantF(dev, 0, size, 1);
    IDirect3DDevice9_DrawPrimitiveUP(dev, D3DPT_TRIANGLESTRIP, 2, quad, sizeof quad[0]);
}

static void sp_pass_to(IDirect3DPixelShader9 *ps, IDirect3DTexture9 *from, int fw, int fh, IDirect3DTexture9 *to) {
    IDirect3DSurface9 *surface = NULL;
    if (SUCCEEDED(IDirect3DTexture9_GetSurfaceLevel(to, 0, &surface))) {
        sp_pass(ps, from, fw, fh, surface);
        IDirect3DSurface9_Release(surface);
    }
}

/* The fit's kernel along one axis: `out` window pixels for `frame` picture pixels from a `prescale` picture. */
static void sp_kernel(float k[4], int out, int frame, int prescale) {
    double ratio = (double)out / ((double)frame * prescale);
    double stretch = ratio < 1.0 ? ratio : 1.0;
    double support;
    if (stretch < 0.5) {
        stretch = 0.5;   /* at most 8 taps; never reached with the prescale chosen below */
    }
    support = 2.0 / stretch;
    k[0] = (float)stretch;
    k[1] = (float)support;
    k[2] = (float)min(8, (int)ceil(2.0 * support));
    k[3] = 0.0f;
}

/* Read finished timings without waiting; step down to 2x when frames run late. */
static void sp_timing(void) {
    int i;
    for (i = 0; i < SP_QUERIES; ++i) {
        UINT64 t0, t1, freq;
        BOOL disjoint;
        if (!g_q_pending[i] || g_q_freq[i] == NULL) {
            continue;
        }
        if (IDirect3DQuery9_GetData(g_q_disjoint[i], &disjoint, sizeof disjoint, 0) != S_OK ||
            IDirect3DQuery9_GetData(g_q_freq[i], &freq, sizeof freq, 0) != S_OK ||
            IDirect3DQuery9_GetData(g_q_begin[i], &t0, sizeof t0, 0) != S_OK ||
            IDirect3DQuery9_GetData(g_q_end[i], &t1, sizeof t1, 0) != S_OK) {
            continue;
        }
        g_q_pending[i] = 0;
        if (disjoint || freq == 0 || t1 < t0) {
            continue;
        }
        g_late_total += 1000.0 * (double)(t1 - t0) / (double)freq;
        if (++g_late_frames >= SP_LATE_FRAMES) {
            if (g_late_total / g_late_frames > SP_LATE_MS && g_stages == 2) {
                g_stages = 1;   /* for the rest of the session */
                SP_RELEASE(g_doubled4);
                SP_RELEASE(g_lattice4);
                SP_RELEASE(g_mid);
            }
            g_late_total = 0.0;
            g_late_frames = 0;
        }
    }
}

