/* VVFP Sharp Picture -- the 4K filter: the game's picture drawn sharp at the screen's own size (the owner,
   2026-11-26: "I prefer a filter made by you. 4k please"; 2026-11-27: filter E, automatic step-down, bars or
   stretch, VV5's window size for every game, the row off by default).  Design and measurements:
   docs/4k-filter-design.md.  PROTOTYPE STAGE: New Believers first.

   WHAT THE GAME DOES.  Each frame its frame routine (A New Home 0x403830 ... New Believers 0x404680) hands SDL 2.0.3
   its finished picture (800x600, or 1024x768 in New Believers) with SDL_UpdateTexture, then SDL_RenderClear,
   SDL_RenderCopy and SDL_RenderPresent, and SDL stretches it to the window nearest-neighbour; the games are not
   DPI aware, so with Windows scaling (150% on many laptops) Windows stretches that again, blurred.

   WHAT THIS COMPANION DOES.
     * The game becomes DPI aware (SetProcessDpiAwarenessContext, system aware; before WinMain), so its window and
       full screen are the screen's real pixels; the game's window opens at 1024x768 times the Windows scaling
       (its SDL_CreateWindow import; New Believers' own size, now for every game), as big on the screen as New
       Believers' window was.
     * Its SDL_UpdateTexture import also copies the finished picture into a texture of a Direct3D 9Ex device of
       our own on the game's window; SDL_RenderClear and SDL_RenderCopy then do nothing and SDL_RenderPresent
       draws the picture with our filter and presents it: the edge-directed 2x scaler (twice, 4x, when the screen
       is more than twice the picture), then a Catmull-Rom fit to the window -- black bars at the sides
       (default), or stretched to fill ("VVFP Sharp Picture.txt" beside it says "stretch").  The GPU time of each
       frame is measured; when frames run late (over 20 ms on average) it steps down to 2x for the rest of the
       session (the owner, 2026-11-27).
     * A click on a black bar does nothing (SDL's event filter drops the press and its release).  Where the mouse
       is in the game's picture is "VVFP Fullscreen Mouse.dll"'s work (Fix Vanilla Bugs); it asks this companion
       for the picture's rectangle (VvfpSharpPictureRect) while the filter draws, so bars and stretch both map.
     * Any Direct3D failure: the filter stops for the session and SDL draws as before (its texture is kept
       up to date every frame).

   ALL OR NONE.  Installed only when SDL2.dll is loaded and reports 2.0.3, the game's frame routine calls its
   SDL_UpdateTexture, SDL_RenderClear, SDL_RenderCopy and SDL_RenderPresent imports in that order, those imports and
   SDL_CreateWindow still hold SDL2.dll's own addresses, and Direct3D 9Ex is there (d3d9.dll from the system
   folder).  No byte of the game's code or of SDL2.dll is written; game files, art and saves are untouched.  No
   debug output. */
