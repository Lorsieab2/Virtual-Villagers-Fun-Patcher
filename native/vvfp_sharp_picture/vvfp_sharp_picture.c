/* ---- checks ----------------------------------------------------------------------------------------------------- */

static HMODULE sp_sdl(void) {
    HMODULE sdl = GetModuleHandleA("SDL2.dll");
    sp_get_version_fn get_version;
    sp_sdl_version version;
    if (sdl == NULL) {
        return NULL;
    }
    get_version = (sp_get_version_fn)GetProcAddress(sdl, "SDL_GetVersion");
    if (get_version == NULL) {
        return NULL;
    }
    version.major = version.minor = version.patch = 0;
    get_version(&version);
    return version.major == 2 && version.minor == 0 && version.patch == 3 ? sdl : NULL;
}

/* The game's import table entry for SDL2.dll's `name`, or NULL. */
static void **sp_import(HMODULE module, const char *name) {
    const unsigned char *base = (const unsigned char *)module;
    const IMAGE_NT_HEADERS *nt = (const IMAGE_NT_HEADERS *)(base + ((const IMAGE_DOS_HEADER *)base)->e_lfanew);
    const IMAGE_DATA_DIRECTORY *dir = &nt->OptionalHeader.DataDirectory[IMAGE_DIRECTORY_ENTRY_IMPORT];
    const IMAGE_IMPORT_DESCRIPTOR *d;
    if (dir->VirtualAddress == 0) {
        return NULL;
    }
    for (d = (const IMAGE_IMPORT_DESCRIPTOR *)(base + dir->VirtualAddress); d->Name != 0; ++d) {
        const IMAGE_THUNK_DATA *names;
        IMAGE_THUNK_DATA *slots;
        if (lstrcmpiA((const char *)(base + d->Name), "SDL2.dll") != 0 || d->OriginalFirstThunk == 0) {
            continue;
        }
        names = (const IMAGE_THUNK_DATA *)(base + d->OriginalFirstThunk);
        slots = (IMAGE_THUNK_DATA *)(base + d->FirstThunk);
        for (; names->u1.AddressOfData != 0; ++names, ++slots) {
            if (!IMAGE_SNAP_BY_ORDINAL(names->u1.Ordinal) &&
                lstrcmpA((const char *)((const IMAGE_IMPORT_BY_NAME *)(base + names->u1.AddressOfData))->Name,
                         name) == 0) {
                return (void **)&slots->u1.Function;
            }
        }
    }
    return NULL;
}

/* 1 when the frame routine's first 0x48 bytes call the thunks of the four imports, in this order. */
static int sp_frame_calls(unsigned int frame, void **const slots[4]) {
    const unsigned char *s = (const unsigned char *)(UINT_PTR)frame;
    int i, found = 0;
    for (i = 0; i < 0x48 && found < 4; ++i) {
        const unsigned char *thunk;
        if (s[i] != 0xE8) {
            continue;
        }
        thunk = s + i + 5 + *(const int *)(s + i + 1);
        if (thunk[0] == 0xFF && thunk[1] == 0x25 && *(void *const *)(thunk + 2) == (void *)slots[found]) {
            ++found;
            i += 4;
        }
    }
    return found == 4;
}

static void sp_set(void **slot, void *value) {
    DWORD old;
    if (VirtualProtect(slot, sizeof *slot, PAGE_READWRITE, &old)) {
        *slot = value;
        VirtualProtect(slot, sizeof *slot, old, &old);
    }
}

/* ---- the picture's place in the window ---------------------------------------------------------------------------- */

static int sp_client(int *w, int *h) {
    RECT r;
    if (g_hwnd == NULL || !GetClientRect(g_hwnd, &r) || r.right <= 0 || r.bottom <= 0) {
        return 0;
    }
    *w = r.right;
    *h = r.bottom;
    return 1;
}

static void sp_fit(int cw, int ch, int *x, int *y, int *w, int *h) {
    if (g_stretch) {
        *x = *y = 0;
        *w = cw;
        *h = ch;
        return;
    }
    if ((long long)cw * g_frame_h >= (long long)ch * g_frame_w) {
        *h = ch;
        *w = (int)(((long long)ch * g_frame_w + g_frame_h / 2) / g_frame_h);
    } else {
        *w = cw;
        *h = (int)(((long long)cw * g_frame_h + g_frame_w / 2) / g_frame_w);
    }
    *x = (cw - *w) / 2;
    *y = (ch - *h) / 2;
}

/* For VVFP Fullscreen Mouse.dll: the game's picture in the window's pixels while this filter draws it; 0 when SDL
   draws (then SDL's own viewport is the picture's place). */
int __stdcall VvfpSharpPictureRect(int *x, int *y, int *w, int *h) {
    int cw, ch;
    if (!g_active || !sp_client(&cw, &ch)) {
        return 0;
    }
    sp_fit(cw, ch, x, y, w, h);
    return 1;
}

/* A press on a black bar does nothing (and nor does its release). */
static int __cdecl sp_filter(void *userdata, void *event) {
    unsigned int type = *(const unsigned int *)event;
    (void)userdata;
    if (g_active && !g_stretch && (type == 0x401u || type == 0x402u)) {   /* SDL_MOUSEBUTTONDOWN / UP */
        unsigned char button = ((const unsigned char *)event)[16] & 7;
        int ex = *(const int *)((const unsigned char *)event + 20), ey = *(const int *)((const unsigned char *)event + 24);
        int cw, ch, x, y, w, h;
        if (type == 0x402u && g_dropped[button]) {
            g_dropped[button] = 0;
            return 0;
        }
        if (type == 0x401u && sp_client(&cw, &ch)) {
            sp_fit(cw, ch, &x, &y, &w, &h);
            if (ex < x || ey < y || ex >= x + w || ey >= y + h) {
                g_dropped[button] = 1;
                return 0;
            }
        }
    }
    return 1;
}

