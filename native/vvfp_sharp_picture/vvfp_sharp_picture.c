/* Draw the picture into the window and present it.  0: our device failed. */
static int sp_draw(void) {
    IDirect3DDevice9 *dev;
    IDirect3DSurface9 *back = NULL;
    IDirect3DTexture9 *big;
    float consts[3][4];
    int cw, ch, fx, fy, fwid, fhei, stages, bw, bh, q;
    HRESULT hr;
    if (IsIconic(g_hwnd) || !sp_client(&cw, &ch)) {
        return 1;   /* nothing to show */
    }
    if (g_dev != NULL && ((int)g_pp.BackBufferWidth != cw || (int)g_pp.BackBufferHeight != ch)) {
        sp_free_device();   /* a new window size (full screen on or off, a resize): a device of the new size */
    }
    if (g_dev == NULL) {
        if (!sp_make_device(cw, ch)) {
            return 0;
        }
        g_frame_ready = 0;
    }
    if (!g_frame_ready) {
        return 1;   /* the next frame's picture is not uploaded yet */
    }
    dev = (IDirect3DDevice9 *)g_dev;
    sp_fit(cw, ch, &fx, &fy, &fwid, &fhei);
    /* 4x only when the picture is shown more than twice its size (and the GPU keeps up); else 2x */
    stages = (g_stages == 2 && fwid > 2 * g_frame_w && fhei > 2 * g_frame_h) ? 2 : 1;
    bw = g_frame_w << stages;
    bh = g_frame_h << stages;
    big = stages == 2 ? g_doubled4 : g_doubled2;
    if (big == NULL || !sp_mid(cw, bh)) {
        return 0;
    }
    q = g_q_next;
    g_q_next = (g_q_next + 1) % SP_QUERIES;
    if (g_q_freq[q] != NULL && !g_q_pending[q]) {
        IDirect3DQuery9_Issue(g_q_disjoint[q], D3DISSUE_BEGIN);
        IDirect3DQuery9_Issue(g_q_begin[q], D3DISSUE_END);
    } else {
        q = -1;
    }
    IDirect3DDevice9_BeginScene(dev);
    IDirect3DDevice9_SetVertexShader(dev, g_vs);
    IDirect3DDevice9_SetFVF(dev, D3DFVF_XYZW);
    IDirect3DDevice9_SetRenderState(dev, D3DRS_CULLMODE, D3DCULL_NONE);
    IDirect3DDevice9_SetRenderState(dev, D3DRS_ZENABLE, D3DZB_FALSE);
    IDirect3DDevice9_SetRenderState(dev, D3DRS_ALPHABLENDENABLE, FALSE);
    IDirect3DDevice9_SetRenderState(dev, D3DRS_SRGBWRITEENABLE, FALSE);
    IDirect3DDevice9_SetSamplerState(dev, 0, D3DSAMP_MINFILTER, D3DTEXF_POINT);
    IDirect3DDevice9_SetSamplerState(dev, 0, D3DSAMP_MAGFILTER, D3DTEXF_POINT);
    IDirect3DDevice9_SetSamplerState(dev, 0, D3DSAMP_MIPFILTER, D3DTEXF_NONE);
    IDirect3DDevice9_SetSamplerState(dev, 0, D3DSAMP_ADDRESSU, D3DTADDRESS_CLAMP);
    IDirect3DDevice9_SetSamplerState(dev, 0, D3DSAMP_ADDRESSV, D3DTADDRESS_CLAMP);
    IDirect3DDevice9_SetSamplerState(dev, 0, D3DSAMP_SRGBTEXTURE, FALSE);
    sp_pass_to(g_step1, g_frame, g_frame_w, g_frame_h, g_lattice2);
    sp_pass_to(g_step2, g_lattice2, 2 * g_frame_w, 2 * g_frame_h, g_doubled2);
    if (stages == 2) {
        sp_pass_to(g_step1, g_doubled2, 2 * g_frame_w, 2 * g_frame_h, g_lattice4);
        sp_pass_to(g_step2, g_lattice4, bw, bh, g_doubled4);
    }
    consts[0][0] = (float)fx;
    consts[0][1] = (float)fy;
    consts[0][2] = (float)fwid;
    consts[0][3] = (float)fhei;
    consts[1][0] = (float)g_frame_w;
    consts[1][1] = (float)g_frame_h;
    consts[1][2] = (float)(1 << stages);
    consts[1][3] = stages == 2 ? -1.5f : -0.5f;   /* the doubled lattice's quarter-pixel shift, undone */
    sp_kernel(consts[2], fwid, g_frame_w, 1 << stages);
    IDirect3DDevice9_SetPixelShaderConstantF(dev, 1, &consts[0][0], 3);
    sp_pass_to(g_rows, big, bw, bh, g_mid);
    sp_kernel(consts[2], fhei, g_frame_h, 1 << stages);
    IDirect3DDevice9_SetPixelShaderConstantF(dev, 3, &consts[2][0], 1);
    if (FAILED(IDirect3DDevice9_GetBackBuffer(dev, 0, 0, D3DBACKBUFFER_TYPE_MONO, &back))) {
        IDirect3DDevice9_EndScene(dev);
        return 0;
    }
    sp_pass(g_columns, g_mid, cw, bh, back);
#ifdef VVFP_TEST
    sp_test_keep(back, cw, ch, stages);
#endif
    IDirect3DSurface9_Release(back);
    IDirect3DDevice9_EndScene(dev);
    if (q >= 0) {
        IDirect3DQuery9_Issue(g_q_end[q], D3DISSUE_END);
        IDirect3DQuery9_Issue(g_q_disjoint[q], D3DISSUE_END);
        IDirect3DQuery9_Issue(g_q_freq[q], D3DISSUE_END);
        g_q_pending[q] = 1;
    }
    hr = IDirect3DDevice9Ex_PresentEx(g_dev, NULL, NULL, NULL, NULL, 0);
    if (hr == D3DERR_DEVICELOST || hr == D3DERR_DEVICEHUNG || hr == D3DERR_DEVICEREMOVED || hr == D3DERR_OUTOFVIDEOMEMORY) {
        return 0;
    }
    sp_timing();
    return 1;
}

