static void sp_read_settings(void) {
    wchar_t path[VVFP_PATCHER_FILES_PATH_CAP];
    char text[64];
    DWORD got = 0;
    HANDLE file;
    g_stretch = 0;
    if (vvfp_patcher_file_path_w(path, VVFP_PATCHER_FILES_PATH_CAP, SP_SETTINGS_FILE) == 0) {
        return;
    }
    file = CreateFileW(path, GENERIC_READ, FILE_SHARE_READ, NULL, OPEN_EXISTING, 0, NULL);
    if (file == INVALID_HANDLE_VALUE) {
        return;
    }
    if (ReadFile(file, text, sizeof text - 1, &got, NULL)) {
        text[got] = 0;
        g_stretch = strstr(text, "stretch") != NULL;
    }
    CloseHandle(file);
}

static void sp_dpi_aware(void) {
    HMODULE user32 = GetModuleHandleA("user32.dll");
    sp_dpi_context_fn context = user32 ? (sp_dpi_context_fn)GetProcAddress(user32, "SetProcessDpiAwarenessContext")
                                       : NULL;
    HDC screen;
    /* system aware (DPI_AWARENESS_CONTEXT_SYSTEM_AWARE is (HANDLE)-2) */
    if (context == NULL || !context((HANDLE)(INT_PTR)-2)) {
        SetProcessDPIAware();
    }
    screen = GetDC(NULL);
    g_dpi = screen != NULL ? GetDeviceCaps(screen, LOGPIXELSX) : 96;
    if (screen != NULL) {
        ReleaseDC(NULL, screen);
    }
    if (g_dpi < 96) {
        g_dpi = 96;
    }
}

