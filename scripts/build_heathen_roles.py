"""New Believers' Heathens in the existing added events: the owner's approved audit -> the roles' "heathens" modes.

The owner (2026-11-23) approved "Heathens in Existing Events (draft for owner)": part 4 judged every villager role of
every added event New Believers can show.  Its rows are kept verbatim (event, role, verdict, the family link the
verdict read) in data/event_collection/heathen_roles_audit.tsv.  The owner's rulings turn each verdict into the role's
mode (docs/event-collection/cie-v6-binary.md 45):

* YES, YES+WORDING -> "allowed" (the words: the engine's automatic swaps, never a hand edit);
* ONLY-IF-ALL-HEATHENS and NO -> "allowed" too: the owner's later word the same day, "heathens can also go in any
  event. They can be only heathens, only believers, a mix of both, outsiders etc all the combinations" (the 8 Living
  Engine "person of faith" events were moved to YES first; every NO followed);
* SAME-FACTION -> "kin": a family role (a kinship relation, a pregnancy's other parent) is a Heathen only beside Heathen
  family and a believer only beside believers (the owner: pregnancy only between two Heathens; a family stays one
  faction);
* ALREADY (an Isolan's role, "heathen_ok") and an event with no villager role: unchanged, nothing written.

The output, data/event_collection/heathen_roles_existing.json, is read beside heathen_roles.json (the Heathen-only
events) by scripts/build_event_collection_features.py apply_heathen_roles.  `--check` fails when the committed file is
not what the table makes.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
AUDIT = ROOT / "data" / "event_collection" / "heathen_roles_audit.tsv"
OUT = ROOT / "data" / "event_collection" / "heathen_roles_existing.json"

VERDICT_MODE = {
    "YES": "allowed",
    "YES+WORDING": "allowed",
    "ONLY-IF-ALL-HEATHENS": "allowed",
    "NO": "allowed",
    "SAME-FACTION": "kin",
    "ALREADY": None,
    "NO-VILLAGER": None,
}

COMMENT = ("New Believers' Heathens in the existing added events (the owner, 2026-11-23; GENERATED by "
           "scripts/build_heathen_roles.py from heathen_roles_audit.tsv, the owner's approved audit -- do not edit). "
           "With the row 'Heathens can be selected in Island Events/Heathen-Exclusive Events' installed, 'allowed': a "
           "believer or an ordinary Heathen; 'kin': the same, but a Heathen only beside Heathen family (the role its "
           "kinship relation names, or its pregnancy's other parent) and a believer only beside believers. Never a "
           "puzzle's Heathen (roles 12-17), never a sick one.")


def audit_rows(path: Path = AUDIT) -> list[tuple[str, str, str, str]]:
    rows = []
    for n, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if not line or line.startswith("#"):
            continue
        parts = line.split("\t")
        if len(parts) != 4 or parts[2] not in VERDICT_MODE:
            raise SystemExit(f"{path.name} line {n}: event, role, verdict, link")
        rows.append((parts[0], parts[1], parts[2], parts[3]))
    return rows


def modes(rows: list[tuple[str, str, str, str]]) -> dict[str, dict[str, str]]:
    out: dict[str, dict[str, str]] = {}
    for event, role, verdict, _link in rows:
        mode = VERDICT_MODE[verdict]
        if mode is None:
            continue
        roles = out.setdefault(event, {})
        if role in roles:
            raise SystemExit(f"{AUDIT.name}: {event} {role} twice")
        roles[role] = mode
    return out


def render(rows: list[tuple[str, str, str, str]]) -> str:
    events = {e: {"roles": dict(sorted(r.items()))} for e, r in sorted(modes(rows).items())}
    return json.dumps({"_comment": COMMENT, "events": events}, indent=1, ensure_ascii=True) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail when the committed file is stale")
    args = ap.parse_args(argv)
    text = render(audit_rows())
    if args.check:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.relative_to(ROOT)} is stale: run scripts/build_heathen_roles.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
