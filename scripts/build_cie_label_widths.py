"""Write how wide a question button's label is in each game, so a label is never refused for being wider than its
button -- only for running off the screen (the owner, 2026-11-13: "i don't care if things run off the button labels
as long as its readable").

Every game draws the labels of its two-button island-event popup in its story font, ldwBurweed27, CENTRED on the
button, and in every game the two buttons are stacked one above the other in the middle of the screen (A New Home and
The Lost Children: the constructor's own placing, native/vvfp_more_island_events/adv_vv1.inc; The Secret City, The
Tree of Life and New Believers: the constructors' own tails run in tests/scrolling_popups_emulation.py put both
buttons at the same x, one above the other, centred on the screen).  So two labels never meet, and a label stays
readable while it fits the screen's width, centred: at most SCREEN - 2 x MARGIN pixels.

The widths are the game's own measure (src/vv_font_glyphs.py text_width: each letter's box plus the font's spacing,
less one spacing; a character the font lacks measures as its first letter), from the stock font pictures
(research/game-images, gitignored: this script runs where they are).  It writes

    data/cie_label_widths.json                         read by src/vv_cie_graph.py (the Check tab)
    native/vvfp_story_upgrades/story_label_widths.h    the in-game Custom Island Event dialog's own check

    python scripts/build_cie_label_widths.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
import vv_font_glyphs as fg  # noqa: E402

NAMES = {1: "A New Home", 2: "The Lost Children", 3: "The Secret City", 4: "The Tree of Life", 5: "New Believers"}
SCREEN = {1: 800, 2: 800, 3: 800, 4: 800, 5: 1024}       # each game's window width (scrolling_popups_emulation)
MARGIN = 16                                              # kept clear at each side of the screen
FONT = "ldwBurweed27"
OUT_JSON = ROOT / "data" / "cie_label_widths.json"
OUT_H = ROOT / "native" / "vvfp_story_upgrades" / "story_label_widths.h"


def measure() -> dict:
    out = {"_about": "Built by scripts/build_cie_label_widths.py: each game's story font (ldwBurweed27) widths of the "
                     "printable ASCII characters (32..126) in pixels, its spacing, and the widest label the screen "
                     "shows whole, centred (screen width less 16 px at each side).", "games": {}}
    for game, name in NAMES.items():
        images = ROOT / "research" / "game-images" / f"Virtual Villagers - {name}" / "Images"
        key = f"vv{game}"
        widths = [fg.text_width(key, FONT, chr(c), images) for c in range(32, 127)]
        spacing = fg.text_width(key, FONT, "AA", images) - 2 * fg.text_width(key, FONT, "A", images)
        out["games"][str(game)] = {"widths": widths, "spacing": spacing, "screen": SCREEN[game],
                                   "max_px": SCREEN[game] - 2 * MARGIN}
        # The table reproduces the game's measure.
        for text in ("Curses schmurses. I'm keeping them.", "W" * 39, "Go investigate!", '"Yes!" said Bea.'):
            assert label_px(out["games"][str(game)], text) == fg.text_width(key, FONT, text, images), (game, text)
    return out


def label_px(table: dict, text: str) -> int:
    """src/vv_cie_graph.py label_px: the game's own measure of `text`."""
    if not text:
        return 0
    w = table["widths"]
    total = sum(w[ord(c) - 32] if 32 <= ord(c) < 127 else w[ord("A") - 32] for c in text)
    return total + table["spacing"] * (len(text) - 1)


def main() -> int:
    data = measure()
    OUT_JSON.write_text(json.dumps(data, indent=1) + "\n", encoding="utf-8", newline="\n")
    lines = ["/* GENERATED by scripts/build_cie_label_widths.py -- do not edit.",
             "   Each game's story font (ldwBurweed27) widths of the printable ASCII characters (32..126), its spacing,",
             "   and the widest question-button label the screen shows whole, centred (the screen less 16 px a side).",
             "   A label may be wider than its button (the owner, 2026-11-13): only the screen limits it. */",
             "", "static const unsigned char CE_LABEL_PX[5][95] = {"]
    for game in range(1, 6):
        w = data["games"][str(game)]["widths"]
        lines.append("    { " + ", ".join(map(str, w)) + " },")
    lines.append("};")
    lines.append("static const int CE_LABEL_SPACING[5] = { "
                 + ", ".join(str(data["games"][str(g)]["spacing"]) for g in range(1, 6)) + " };")
    lines.append("static const int CE_LABEL_MAX_PX[5] = { "
                 + ", ".join(str(data["games"][str(g)]["max_px"]) for g in range(1, 6)) + " };")
    OUT_H.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(OUT_JSON.relative_to(ROOT), OUT_H.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
