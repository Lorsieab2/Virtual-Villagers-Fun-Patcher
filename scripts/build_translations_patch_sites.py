"""Writes native/vvfp_translations/tr_patch_sites.inc (the trusted list of exe-patch text locations) and
tr_key_stems.inc (the stems of the rows a companion asks for by key only).

tr_key_stems.inc: a row with "route": "key" in data/translations/patcher_strings.json is found by its stem
(VvfpTranslateKey); VVFP Translations.dll keeps it out of the content map, where its English ("%s of %s",
"Disease") would also translate every other text of that shape.

tr_patch_sites.inc:

VVFP Translations.dll writes a "patch/0x<va>" translation over the text an exe patch put at that address,
and ONLY for the addresses (and English texts) in this list, per game. A translation file names the address
and the hash of the English itself, so without this list a crafted file could aim a row at code instead of
text. The list comes from data/translations/patcher_strings.json (the patcher's own text inventory, made by
scripts/build_patch_text_inventory.py), so run that first when a patch's text changes.

    python scripts/build_translations_patch_sites.py            # write the .inc
    python scripts/build_translations_patch_sites.py --check    # fail when the .inc is out of date
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STRINGS = ROOT / "data" / "translations" / "patcher_strings.json"
OUT = ROOT / "native" / "vvfp_translations" / "tr_patch_sites.inc"
KEYS_OUT = ROOT / "native" / "vvfp_translations" / "tr_key_stems.inc"
STEM = re.compile(r"^patch/0x([0-9a-fA-F]{1,8})(?:\.v\d+)?$")


def sha32(text: str) -> int:
    """The key's hash: the first 8 hex digits of the SHA-256 of the English (UTF-8)."""
    return int(hashlib.sha256(text.encode("utf-8")).hexdigest()[:8], 16)


def build() -> str:
    rows = json.loads(STRINGS.read_text(encoding="utf-8"))["strings"]
    per_game: dict[int, set[tuple[int, int]]] = {n: set() for n in range(1, 6)}
    for row in rows:
        match = STEM.match(row.get("stem", ""))
        if not match:
            continue
        va = int(match.group(1), 16)
        for game in row.get("games") or []:
            per_game[int(game[2:])].add((va, sha32(row["english"])))
    lines = [
        "/* tr_patch_sites.inc -- generated by scripts/build_translations_patch_sites.py; do not edit.",
        "",
        "   Per game, every address where an exe patch writes visible text (\"patch/0x<va>\" rows), with the hash",
        "   of that English. VVFP Translations.dll writes a translation over such text only at a listed",
        "   (address, hash) pair: a translation file cannot aim a row at code. Each array ends with a zero",
        "   entry. */",
        "",
    ]
    for number in range(1, 6):
        lines.append(f"static const tr_patch_site TR_PATCH_SITES_VV{number}[] = {{")
        for va, h in sorted(per_game[number]):
            lines.append(f"    {{ 0x{va:06X}u, 0x{h:08X}u }},")
        lines.append("    { 0 },")
        lines.append("};")
        lines.append("")
    return "\n".join(lines)


def build_key_stems() -> str:
    rows = json.loads(STRINGS.read_text(encoding="utf-8"))["strings"]
    stems = sorted({row["stem"] for row in rows if row.get("route") == "key"})
    lines = [
        "/* tr_key_stems.inc -- generated by scripts/build_translations_patch_sites.py; do not edit.",
        "",
        "   The stems of the companions' rows that are asked for by key only (\"route\": \"key\" in",
        "   data/translations/patcher_strings.json).  Such a row is never put in the content map. */",
        "",
        "static const char *const TR_KEY_STEMS[] = {",
    ]
    lines += [f'    "{stem}",' for stem in stems]
    lines += ["    NULL", "};", ""]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = build()
    keys = build_key_stems()
    if args.check:
        for path, expected in ((OUT, text), (KEYS_OUT, keys)):
            if not path.is_file() or path.read_text(encoding="utf-8").replace("\r\n", "\n") != expected:
                print(f"{path.name} is out of date: run scripts/build_translations_patch_sites.py")
                return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    KEYS_OUT.write_text(keys, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} and {KEYS_OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
