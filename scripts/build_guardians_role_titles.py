"""New Believers' puzzle Heathens' titles as Guardians of Isola Rewrite names them in the game, for the logs.

The owner (2026-11-23): with the rewrite on, the logs' "Special villager" line names a puzzle Heathen by the
rewrite's OWN in-game name ("Esteemed Isolan Doctor", "Chief of the Native Isola Tribe", ...), exactly as the game
shows it.  Taken from the rewrite's text (data/guardians_of_isola/new/Assets/sm.xml, the game's eSayHeathen* rows),
never typed by hand: this script writes

    native/shared/guardians_role_titles.h   the companions' table (special_title.h, isolan_log_words.h)
    src/vv_guardians_role_titles.py         the patcher's readers' table (vv_isolan_words.py)

tests/test_guardians_heathen_wording.py checks both still agree with the rewrite's sm.xml.
Usage: python scripts/build_guardians_role_titles.py
"""
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BASE = ROOT / "data" / "guardians_of_isola" / "base" / "Assets" / "sm.xml"
NEW = ROOT / "data" / "guardians_of_isola" / "new" / "Assets" / "sm.xml"
HEADER = ROOT / "native" / "shared" / "guardians_role_titles.h"
MODULE = ROOT / "src" / "vv_guardians_role_titles.py"

# The six puzzle roles in the order of native/shared/special_title.h's VV5_HEATHENS (roles 12..17), each with the
# game's own text row that names it.
ROWS = (
    (12, "eSayHeathenMasterDoctor"),
    (13, "eSayHeathenChief"),
    (14, "eSayHeathenMasterResearcher"),
    (15, "eSayHeathenMasterBuilder"),
    (16, "eSayHeathenMasterFarmer"),
    (17, "eSayHeathenMasterParent"),
)


def load(path: Path) -> dict[str, str]:
    text = path.read_text(encoding="cp1252")
    return {m.group(1): m.group(2).strip() for m in re.finditer(r'<Text id="([^"]+)">(.*?)</Text>', text, re.S)}


def titles() -> list[tuple[int, str, str]]:
    base, new = load(BASE), load(NEW)
    return [(role, base[row], new[row]) for role, row in ROWS]


def c_string(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> None:
    rows = titles()
    lines = [
        "/* GENERATED by scripts/build_guardians_role_titles.py from data/guardians_of_isola/{base,new}/Assets/sm.xml -- do",
        "   not edit.  New Believers' puzzle Heathens (roles 12..17): the game's own title, and the Guardians of Isola",
        "   Rewrite's own in-game name for it (the owner, 2026-11-23: the logs name them as the game does with the",
        "   rewrite on).  tests/test_guardians_heathen_wording.py checks it against the rewrite's sm.xml. */",
        "#ifndef VV_GUARDIANS_ROLE_TITLES_H",
        "#define VV_GUARDIANS_ROLE_TITLES_H",
        "",
        "static const char *const VV5_ROLE_TITLES_HEATHEN[6] = {",
        *[f"    {c_string(b)},    /* role {r} */" for r, b, _ in rows],
        "};",
        "static const char *const VV5_ROLE_TITLES_ISOLAN[6] = {",
        *[f"    {c_string(n)},    /* role {r} */" for r, _, n in rows],
        "};",
        "",
        "#endif",
        "",
    ]
    HEADER.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    module = [
        '"""GENERATED by scripts/build_guardians_role_titles.py from data/guardians_of_isola/{base,new}/Assets/sm.xml -- do',
        "not edit.  New Believers' puzzle Heathens' titles (roles 12..17): the game's own, then the Guardians of Isola",
        "Rewrite's own in-game name (the logs with the rewrite on; vv_isolan_words reads both).\"\"\"",
        "",
        "ROLE_TITLES = {",
        *[f"    {r}: ({b!r}, {n!r})," for r, b, n in rows],
        "}",
        "",
    ]
    MODULE.write_text("\n".join(module), encoding="utf-8", newline="\n")
    print(HEADER)
    print(MODULE)


if __name__ == "__main__":
    main()
