"""Write docs/custom-island-event-villager-actions.md: every Villager Changes action, per game.

Read from tests/cie_behaviour_catalog.json, which tests/test_cie_behaviour_labels.py pins against
each game's adapter table (native/vvfp_story_upgrades/story_c<N>.inc).  Run from the repository
root:

    python scripts/build_cie_actions_doc.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "tests" / "cie_behaviour_catalog.json"
DOC = ROOT / "docs" / "custom-island-event-villager-actions.md"
GAMES = {1: "A New Home", 2: "The Lost Children", 3: "The Secret City", 4: "The Tree of Life", 5: "New Believers"}
GROUPS = {"GENERAL": "General", "WORK": "Work", "LEISURE": "Leisure", "CELEBRATION": "Celebration and dance",
          "DEVOTION": "Devotion", "FAMILY": "Family", "CHILDREN": "Children", "HEALTH": "Health, food and drink",
          "CURIOSITY": "Curiosity", "MOOD": "Moods and idle", "STORY": "Puzzles and story"}
ORDER = list(GROUPS)


def _start(game: int, row: dict) -> str:
    kind = row["kind"]
    if kind == "ACT_STOP":
        return "the game's stop routine"
    if kind == "ACT_RECOVER":
        return "cured, full health"
    if kind == "ACT_DO":
        return f"action {row['arg']}"
    args = {"ACT_CALL": "", "ACT_EFFECT": "", "ACT_CALL_ARG": f", {row['arg']}",
            "ACT_CALL_ARG2": f", {row['arg']}, 0"}[kind]
    return f"0x{row['routine']:X}(villager{args})"


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def render() -> str:
    data = json.loads(CATALOG.read_text(encoding="utf-8"))
    out = [
        "# Custom Island Event: every villager action",
        "",
        "Generated by `scripts/build_cie_actions_doc.py` from `tests/cie_behaviour_catalog.json`; do not "
        "edit by hand.",
        "",
        "The owner (2026-10-21): \"add all villager actions/behaviors to the Villager Changes section in "
        "the Custom Island Event. Especially 'Celebrating'\", then \"Behaviors from: Island events, Puzzles, "
        "Golden Child behaviors, Heathen behaviors, Chief behaviors -- literally anything villagers can do, "
        "on everyone regardless!!!\"",
        "",
        "Each game's list holds every action the game's own code can start for one villager -- its jobs "
        "and idle actions, the island events', the puzzles', the Golden Child's, the Tribal Chief's and "
        "the Heathens' -- offered for any villager.  Each label is the text the Details screen shows once "
        "the villager does it (an action that can show more than one text names them; a note in brackets "
        "says where an action comes from or what it gives).  The villager is stopped first and the "
        "game's own starter runs (A New Home and The Lost Children: the starter routine with the "
        "villager's index; the later games: the do-action routine with the action id and an argument "
        "block of zeros).",
        "",
        "An action that may harm the game or the save ends **(Unsafe)**: choosing it shows the reason "
        "and advises backing up the save first (Back Up Saves), OK / Cancel.  One that would need a "
        "missing object is refused when the event happens (the villager is not changed) instead of "
        "crashing the game.",
        "",
        "Evidence: `tests/test_cie_behaviour_labels.py` re-derives every label's text from the stock "
        "executables; `tests/test_cie_behaviours_emulated.py` starts every action in an emulated stock "
        "executable for an adult, a child and (New Believers) a Heathen and checks the Details text "
        "and action code.  Not run in the game.",
        "",
    ]
    for game, name in GAMES.items():
        rows = data[str(game)]
        unsafe = sum(1 for r in rows if r["unsafe"])
        out += [f"## {name}", "",
                f"{len(rows)} actions, {unsafe} of them (Unsafe).  Listed as the dialog shows them: by group, "
                "then label.", "",
                "| Group | Label | Started as | Why (Unsafe) |", "|---|---|---|---|"]
        for r in sorted(rows, key=lambda r: (ORDER.index(r["group"]), r["label"].lower())):
            why = r["unsafe"] or ""
            if r.get("guard"):
                why += f" (refused while the dword at 0x{r['guard']['va']:X} is 0)"
            out.append(f"| {GROUPS[r['group']]} | {_cell(r['label'])} | {_start(game, r)} | {_cell(why)} |")
        events = data.get(f"{game}_island_events") or []
        if events:
            out += ["", "Island events and the actions they start:", ""]
            for e in events:
                out.append(f"- {_cell(e['event'])}: {', '.join(e['actions']) or '(an idle state the game acts on)'}")
        left = data.get(f"{game}_left_out") or []
        if left:
            out += ["", "Not offered (no way to start them for one chosen villager):", ""]
            for e in left:
                out.append(f"- {_cell(e['what'])}: {_cell(e['reason'])}")
        out.append("")
    return "\n".join(out)


def main() -> None:
    DOC.write_text(render(), encoding="utf-8", newline="\n")
    print(f"wrote {DOC.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
