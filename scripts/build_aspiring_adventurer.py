"""Write "The Aspiring Adventurer" (the owner's island event, 2026-11-12, all five games).

From the one source of its words and odds, src/vv_aspiring_adventurer.py, this writes:

  * native/vvfp_aspiring_adventurer/adv_text.inc -- the companion's text table: every piece in its male and female
    form (the stranger's sentence in the stranger's), with its translation key;
  * the translation template's rows for those keys (data/translations/patcher_strings.json), so every word the event
    shows is translatable as the other companions' text is (each piece by its key, VvfpTranslateKeyText);
  * data/vvN_aspiring_adventurer_event_feature.json, the five rows, pinning the built DLL by SHA-256.

    python scripts/build_aspiring_adventurer.py            # build the DLL (scripts/build_vvfp_aspiring_adventurer.ps1)
    python scripts/build_aspiring_adventurer.py --no-build # pin what is built
    python scripts/build_aspiring_adventurer.py --text     # only the text table and the template rows
"""
from __future__ import annotations

import hashlib
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
import vv_aspiring_adventurer as adv  # noqa: E402

NATIVE = ROOT / "native" / "vvfp_aspiring_adventurer"
TEXT_INC = NATIVE / "adv_text.inc"
PATCHER_STRINGS = ROOT / "data" / "translations" / "patcher_strings.json"
DLL_NAME = "VVFP Aspiring Adventurer.dll"
DLL = ROOT / "assets" / "aspiring_adventurer" / DLL_NAME
GAMES = (1, 2, 3, 4, 5)
TITLES = {1: "A New Home", 2: "The Lost Children", 3: "The Secret City", 4: "The Tree of Life", 5: "New Believers"}
INSTALLED_BY = f"{DLL_NAME}, VvfpStartup (started by VVFP Startup.dll, second word)"


def feature_id(game: int) -> str:
    return f"vv{game}_aspiring_adventurer_event"


def c_string(text: str) -> str:
    out = []
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif 32 <= ord(ch) < 127:
            out.append(ch)
        else:
            raise ValueError(f"not ASCII: {ch!r}")
    return '"' + "".join(out) + '"'


def text_inc() -> str:
    lines = [
        "/* GENERATED by scripts/build_aspiring_adventurer.py from src/vv_aspiring_adventurer.py -- do not edit.",
        "",
        "   The Aspiring Adventurer's words (the owner's, 2026-11-12): each piece's key (its translation row's stem)",
        "   and English, for a male and a female adventurer (STRANGER: a male and a female stranger), the names as %s",
        "   in the order `names` gives (n the adventurer, f the friend) and an amount as %d. */",
        "",
        "enum {",
    ]
    for key, _ in adv.TEXTS:
        lines.append(f"    ADV_{key},")
    lines += ["    ADV_PIECES", "};", "", "typedef struct {",
              "    const char *stem[2];             /* [0] male, [1] female (the same when the piece has no pronoun) */",
              "    const char *english[2];",
              "    const char *names;               /* \"n\", \"nf\", ...: what each %s is */",
              "} adv_piece_text;", "", "static const adv_piece_text ADV_TEXT[ADV_PIECES] = {"]
    for key, _ in adv.TEXTS:
        forms = adv.forms(key)
        m, f = (forms[0], forms[-1])
        names = "".join(adv.names_in(key))
        lines.append(f"    {{ {{ {c_string(adv.stem(key, m))}, {c_string(adv.stem(key, f))} }},")
        lines.append(f"      {{ {c_string(adv.english(key, m))},")
        lines.append(f"        {c_string(adv.english(key, f))} }},")
        lines.append(f"      {c_string(names)} }},")
    lines += ["};", ""]
    return "\n".join(lines)


def template_rows() -> list[dict]:
    out = []
    for stem, key, english, names in adv.rows():
        notes = ["a patcher text shown by the game in its island-event popup"]
        k = 1
        for who in names:
            notes.append(f"%{k} = text (person: {'the adventurer' if who == 'n' else 'the friend'})")
            k += 1
        if "%d" in english:
            notes.append(f"%{k} = a number (number)")
        form = stem.rsplit(".", 1)[-1]
        if form in ("m", "f"):
            who = "the stranger" if key == "STRANGER" else "the adventurer"
            notes.append(f"{who} is {'male' if form == 'm' else 'female'}")
        if key in ("LABEL_A", "LABEL_B"):
            notes[0] = "a button of the game's island-event popup"
        out.append({"stem": stem, "english": english, "games": ["vv5"] if key in ("L2_HEATHENS", "L2_ISOLANS")
                    else (["vv1", "vv2", "vv3", "vv4"] if key == "L2_OTHER" else ["vv1", "vv2", "vv3", "vv4", "vv5"]),
                    "mechanism": "b", "context": adv.CONTEXT, "notes": "; ".join(notes), "route": "key"})
    return out


def write_template_rows() -> None:
    document = json.loads(PATCHER_STRINGS.read_text(encoding="utf-8"))
    rows = document["strings"]
    ours = template_rows()
    ours_by = {r["stem"]: r for r in ours}
    index = {r["stem"]: i for i, r in enumerate(rows)}
    # Each row stays where it was (a stable file); new ones go at the end; a row of ours no longer made goes.
    out = []
    for r in rows:
        if r["stem"] in ours_by:
            out.append(ours_by[r["stem"]])
        elif not r["stem"].startswith(adv.STEM + "."):
            out.append(r)
    out += [r for r in ours if r["stem"] not in index]
    document["strings"] = out
    PATCHER_STRINGS.write_text(json.dumps(document, indent=1, ensure_ascii=False) + "\n", encoding="utf-8",
                               newline="\n")
    print("wrote", PATCHER_STRINGS.relative_to(ROOT))


def write_text_inc() -> None:
    NATIVE.mkdir(parents=True, exist_ok=True)
    TEXT_INC.write_text(text_inc(), encoding="utf-8", newline="\n")
    print("wrote", TEXT_INC.relative_to(ROOT))


def main() -> None:
    write_text_inc()
    write_template_rows()
    if "--text" in sys.argv[1:]:
        return
    if "--no-build" not in sys.argv[1:]:
        subprocess.run(["powershell", "-NoProfile", "-ExecutionPolicy", "Bypass", "-File",
                        str(ROOT / "scripts" / "build_vvfp_aspiring_adventurer.ps1")], check=True)
    import build_aspiring_adventurer_rows as rows_mod  # noqa: E402  (the rows: scripts/, beside this)
    sha = hashlib.sha256(DLL.read_bytes()).hexdigest().upper()
    for game in GAMES:
        path = ROOT / "data" / f"{feature_id(game)}_feature.json"
        path.write_text(json.dumps(rows_mod.row(game, sha), indent=2, ensure_ascii=False) + "\n", encoding="utf-8",
                        newline="\n")
        print("wrote", path.relative_to(ROOT))


if __name__ == "__main__":
    sys.path.insert(0, str(ROOT / "scripts"))
    main()
