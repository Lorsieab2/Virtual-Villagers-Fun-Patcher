"""Writes native/vvfp_text_fixes/tf_fixes.inc (the companion's table) from data/vanilla_text_fixes.json.

Fix Vanilla Bugs' game-typo fixes (the owner, 2026-11-17): each entry is {game, the string table name (The Secret
City .. New Believers) or row id (A New Home, The Lost Children), the exact stock text, the fixed text}.  The texts
are the games' own bytes (Windows-1252).  tests/test_text_fixes.py checks the committed file matches.

    python scripts/build_text_fixes_table.py          # write
    python scripts/build_text_fixes_table.py --check  # exit 1 when the committed file differs
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data" / "vanilla_text_fixes.json"
OUT = ROOT / "native" / "vvfp_text_fixes" / "tf_fixes.inc"
GAME_TEXT = "cp1252"


def c_string(text: str, indent: str) -> str:
    """`text` as adjacent C string literals (each piece at most ~100 bytes, split after a line break)."""
    raw = text.encode(GAME_TEXT)
    pieces, piece = [], ""
    for byte in raw:
        ch = chr(byte)
        if ch == "\n":
            piece += "\\n"
        elif ch == '"':
            piece += '\\"'
        elif ch == "\\":
            piece += "\\\\"
        elif 0x20 <= byte < 0x7F and ch != "?":
            piece += ch
        else:
            piece += f"\\{byte:03o}"            # octal: never runs into the next character
        if ch == "\n" or len(piece) >= 100:
            pieces.append(piece)
            piece = ""
    if piece or not pieces:
        pieces.append(piece)
    return ("\n" + indent).join(f'"{p}"' for p in pieces)


def render() -> str:
    doc = json.loads(DATA.read_text(encoding="utf-8"))
    lines = [
        "/* Generated by scripts/build_text_fixes_table.py from data/vanilla_text_fixes.json -- do not edit.",
        "   {game, string table name (VV3-VV5) or NULL, row id (VV1, VV2) or 0, the stock text, the fixed text} */",
        "static const tf_fix TF_FIXES[] = {",
    ]
    for fix in doc["fixes"]:
        game, stem = int(fix["game"]), fix["stem"]
        source, key = stem.split("/", 1)
        if source == "table":
            name, ident = "NULL", f"{int(key)}u"
        elif source == "sm":
            name, ident = f'"{key}"', "0u"
        else:
            raise ValueError(f"unsupported stem {stem!r}")
        reason = fix["reason"].replace("*/", "* /")
        lines.append(f"    /* {stem}: {reason} */")
        lines.append(f"    {{ {game}, {name}, {ident},")
        lines.append("      " + c_string(fix["old"], "      ") + ",")
        lines.append("      " + c_string(fix["new"], "      ") + " },")
    lines.append("};")
    pool = sum(len(f["new"].encode(GAME_TEXT)) + 1 for f in doc["fixes"])
    lines.append("/* every fixed text with its terminator: the size of the companion's own writable copies */")
    lines.append(f"#define TF_POOL_SIZE {pool}u")
    return "\n".join(lines) + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv[1:]:
        current = OUT.read_text(encoding="utf-8") if OUT.is_file() else ""
        if current != text:
            print(f"{OUT.relative_to(ROOT)} is out of date: run scripts/build_text_fixes_table.py")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
