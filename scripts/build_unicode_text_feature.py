def row(game: int, dll_sha: str, tables: dict) -> dict:
    g = tables["games"][f"vv{game}"]
    fonts = g["fonts"]
    text = g["text_input"]
    return {
        "id": f"vv{game}_unicode_text",
        "enabled": True,
        "catalog_enabled": True,
        "catalog_hidden": False,
        "game_id": f"vv{game}",
        "name": NAME,
        "description": description(game),
        "output_tag": "Unicode Text",
        "behavior_changes": [
            f"The font constructor ({g['ctor']}) runs unchanged, then for the game's two fonts -- ldwBurweed27 "
            f"(stock glyph table {fonts['ldwBurweed27']['table']}) and ldwarialbold ({fonts['ldwarialbold']['table']}) "
            "-- every printable Windows-1252 character the font lacks is made (src/vv_font_glyphs.py, run in C by "
            "native/vvfp_unicode_text/glyphs.inc) and added: as new rows under the loaded font picture (a new "
            "SDL surface of the same format; the old one is freed) and as new entries in a copy of the glyph "
            "table, with the font's 256-entry index pointing each code at its letter. NBSP draws as the space "
            "and the soft hyphen as '-'.",
            "Every text draw and measure reads letters through the font's glyph lookup, so names, the Details "
            "screen, popups, the Tech screen, logs shown in the game and word wrapping all draw the new letters "
            "and measure them by their real widths, in every text colour.",
            f"The SDL_TEXTINPUT case ({text['site']}) posts a typed text of ONE character that Windows-1252 has as "
            "that byte (0x80-0xFF zero-extended, which the game's text boxes already accept: they take 0x20..0xFF); "
            "plain ASCII is posted exactly as before, and anything else is skipped as before.",
        ],
        "explicit_non_changes": [
            "No executable byte is patched: the companion replaces the constructor's first instructions and the "
            "SDL_TEXTINPUT case's first seven bytes at run time, all or none, only after verifying their stock "
            "bytes, and installs nothing on a different build.",
            "The game's pictures (Images\\ldwBurweed27.png, Images\\ldwarialbold.png) are never changed; the new "
            "letters exist only in the game's memory. Nothing of the game's art is shipped.",
            "Every character stays one byte: no name or text box holds more bytes than before, and nothing is "
            "cut inside a character. Saves, villager records and the patcher's files are never written.",
            "A font that is not one of the two, not 32-bit, or whose letters cannot be made is left exactly as "
            "the game built it; a fault while adding letters leaves the font stock.",
        ],
        "companion_files": [
            {"source": f"assets/unicode_text/{DLL_NAME}", "destination": DLL_NAME, "sha256": dll_sha},
        ],
        "patches": [],
        "runtime_detours": [
            {"va": g["ctor"], "stock_bytes": g["ctor_bytes"][:2 * g["ctor_len"]],
             "routine": "the LDW font constructor (thiscall: font; picture name, glyph table, spacing)",
             "installed_by": f"{DLL_NAME}, VvfpStartup (started by VVFP Startup.dll, second word)"},
            {"va": text["site"], "stock_bytes": text["stock_bytes"],
             "routine": "the event pump's SDL_TEXTINPUT case (lea eax, [esp + text]; lea edx, [eax + 1])",
             "installed_by": f"{DLL_NAME}, VvfpStartup (started by VVFP Startup.dll, second word)"},
        ],
    }


def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest().upper()


def main() -> None:
    if "--no-build" not in sys.argv[1:]:
        subprocess.run(["powershell", "-NoProfile", "-ExecutionPolicy", "Bypass", "-File",
                        str(ROOT / "scripts" / "build_vvfp_unicode_text.ps1")], check=True)
    tables = json.loads(TABLES.read_text(encoding="utf-8"))
    digest = sha(DLL)
    for game in GAMES:
        out = ROOT / "data" / f"vv{game}_unicode_text_feature.json"
        out.write_text(json.dumps(row(game, digest, tables), indent=2) + "\n", encoding="utf-8", newline="\n")
        print("wrote", out.relative_to(ROOT), digest)


if __name__ == "__main__":
    main()
