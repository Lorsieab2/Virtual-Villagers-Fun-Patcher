"""Write data/vv<N>_unicode_text_feature.json: "Render Unicode with In-Game Fonts", all five games (the
owner, 2026-11-01).

The behaviour lives in one companion, "VVFP Unicode Text.dll" (native/vvfp_unicode_text), started by VVFP
Startup.dll from its second word of companions (native/shared/startup_companions_2.h).  It patches no
executable byte: it detours the font constructor and the SDL_TEXTINPUT case at run time, after checking
their stock bytes (data/font_glyph_tables.json, generated by scripts/build_font_glyph_tables.py).

One command after the DLL's source changes: this script builds it (scripts/build_vvfp_unicode_text.ps1) and
pins it by SHA-256 in all five rows.  --no-build pins what is already built.
"""
from __future__ import annotations

import hashlib
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DLL_NAME = "VVFP Unicode Text.dll"
DLL = ROOT / "assets" / "unicode_text" / DLL_NAME
TABLES = ROOT / "data" / "font_glyph_tables.json"
GAMES = (1, 2, 3, 4, 5)
NAME = "Render Unicode with In-Game Fonts"

COVERAGE = {
    1: "A New Home's two fonts hold only A-Z, a-z, 0-9 and ! \" ' , . ? / ` : -, so this adds 145 characters "
       "to each, the other ASCII signs (# $ % & ( ) * + ; < = > @ [ \\ ] ^ _ { | } ~) among them",
    2: "The Lost Children's two fonts hold only A-Z, a-z, 0-9 and ! \" ' , . ? / ` : -, so this adds 145 "
       "characters to each, the other ASCII signs (# $ % & ( ) * + ; < = > @ [ \\ ] ^ _ { | } ~) among them",
    3: "The Secret City's fonts already hold the Latin-1 letters, so this adds the 29 they lack: the euro, "
       "the curly quotes and dashes, … • † ‡ ‰ ™, Š š Ž ž "
       "Ÿ Œ œ ƒ and the inverted exclamation mark",
    4: "The Tree of Life's fonts already hold the Latin-1 letters, so this adds the 28 they lack: the euro, "
       "the curly quotes and dashes, … • † ‡ ‰ ™, Š š Ž ž "
       "Ÿ Œ œ and ƒ",
    5: "New Believers' fonts already hold the Latin-1 letters, so this adds the 28 they lack: the euro, "
       "the curly quotes and dashes, … • † ‡ ‰ ™, Š š Ž ž "
       "Ÿ Œ œ and ƒ",
}


