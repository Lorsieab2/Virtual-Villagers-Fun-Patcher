"""Write each game's own first-name lists -- the two lists its villager creator draws a new villager's name from
(A New Home 0x43B967 / The Lost Children 0x44B727 / The Secret City 0x45C6A1 / The Tree of Life 0x465DE3 / New
Believers 0x46F6C3: male first, then female; scripts/vvfp_consistency_check.py NAME_LISTS) -- for the named
strangers of Custom Island Events format version 6 (docs/event-collection/cie-v6-binary.md 16).

Each list is ONE comma-separated string in the stock executable ("Achak,Ahi,...,").  This script finds both in the
stock executables (research/stock-executables, gitignored: it runs where they are), with the virtual address each
string has once the game is loaded, and writes

    data/cie_villager_names.json                         read by src/vv_cie_graph.py (the worst case, the editor)
    native/vvfp_story_upgrades/story_villager_names.h   the engine: the lists' addresses (read from the game at run
                                                        time) and the same lists, used when the game's own cannot
                                                        be read

tests/test_cie_graph_v6.py pins the JSON against the stock executables.

    python scripts/build_cie_villager_names.py
"""
from __future__ import annotations

import json
import re
from pathlib import Path

import pefile

ROOT = Path(__file__).resolve().parents[1]
STOCK = ROOT / "research" / "stock-executables"
EXES = {1: "Virtual Villagers - A New Home.exe", 2: "Virtual Villagers - The Lost Children.exe",
        3: "Virtual Villagers - The Secret City.exe", 4: "Virtual Villagers - The Tree of Life.exe",
        5: "Virtual Villagers - New Believers.exe"}
OUT_JSON = ROOT / "data" / "cie_villager_names.json"
OUT_H = ROOT / "native" / "vvfp_story_upgrades" / "story_villager_names.h"
LIST_RE = re.compile(rb"(?:[A-Z][a-z]+,){60,}[A-Z]?[a-z]*,?")


def find_lists(game: int) -> dict:
    """The male and female lists of `game`'s stock executable: their text and virtual addresses."""
    path = STOCK / EXES[game]
    data = path.read_bytes()
    pe = pefile.PE(str(path), fast_load=True)
    found = [(m.start(), m.group(0).decode()) for m in LIST_RE.finditer(data)]
    # The creator's two lists are the first pair in the file (male, then female); the third list after them is the
    # last-name list Villagers Have Last Names uses.
    (m_off, male), (f_off, female) = found[0], found[1]
    va = lambda off: pe.get_rva_from_offset(off) + pe.OPTIONAL_HEADER.ImageBase  # noqa: E731
    split = lambda s: [x for x in s.split(",") if x]  # noqa: E731
    return {"male_va": va(m_off), "female_va": va(f_off), "male_bytes": len(male), "female_bytes": len(female),
            "male": split(male), "female": split(female)}


def main() -> None:
    out = {"_about": "Built by scripts/build_cie_villager_names.py: each game's own first-name lists (the villager "
                     "creator's, male then female), with the virtual address of each comma-separated string in the "
                     "stock executable.  A named stranger (cie-v6-binary.md 16) draws from them.",
           "games": {}}
    lines = ["/* GENERATED by scripts/build_cie_villager_names.py -- do not edit.  Each game's own first-name lists",
             "   (cie-v6-binary.md 16): where the game keeps each one (read at run time), its bytes, and the same list",
             "   for when the game's own cannot be read. */", "",
             "static const unsigned int CG_NAMES_VA[6][2] = { { 0, 0 },"]
    texts = []
    for game in sorted(EXES):
        d = find_lists(game)
        out["games"][str(game)] = d
        lines.append(f"    {{ 0x{d['male_va']:X}u, 0x{d['female_va']:X}u }},")
        texts.append((",".join(d["male"]) + ",", ",".join(d["female"]) + ","))
    lines[-1] = lines[-1].rstrip(",") + " };"
    lines.append("static const unsigned int CG_NAMES_BYTES[6][2] = { { 0, 0 },")
    for game in sorted(EXES):
        d = out["games"][str(game)]
        lines.append(f"    {{ {d['male_bytes']}u, {d['female_bytes']}u }},")
    lines[-1] = lines[-1].rstrip(",") + " };"
    lines.append("static const char *const CG_NAMES_TEXT[6][2] = { { \"\", \"\" },")
    for male, female in texts:
        lines.append(f"    {{ \"{male}\",")
        lines.append(f"      \"{female}\" }},")
    lines[-1] = lines[-1].rstrip(",") + " };"
    lines.append("")
    OUT_JSON.write_bytes((json.dumps(out, indent=1) + "\n").encode())
    OUT_H.write_bytes("\n".join(lines).encode())
    print(OUT_JSON, OUT_H)


if __name__ == "__main__":
    main()
