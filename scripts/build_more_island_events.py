def cave_text_inc() -> str:
    lines = [
        "/* GENERATED by scripts/build_more_island_events.py from src/vv_cave_explorers.py -- do not edit.",
        "",
        "   The Cave Explorers' words (the owner's, 2026-11-12): each piece's key (its translation row's stem) and",
        "   English in each form -- index sum(female_k << k), k over `pronouns`, the villagers whose pronouns the piece",
        "   uses -- the names as %s in the order `names` gives (cave_core.inc cave_index: a name1, b name2, s the",
        "   screamer, o the other, r the finder, c the one who slips, d the other) and an amount as %d. */",
        "",
        "enum {",
    ]
    for key, _ in cave.TEXTS:
        lines.append(f"    CAVE_{key},")
    lines += ["    CAVE_PIECES", "};", "", "typedef struct {",
              "    const char *stem[4];",
              "    const char *english[4];",
              "    const char *names;               /* what each %s is */",
              "    const char *pronouns;            /* whose sex picks the form, bit k the k-th */",
              "} cave_piece_text;", "", "static const cave_piece_text CAVE_TEXT[CAVE_PIECES] = {"]
    for key, _ in cave.TEXTS:
        forms = cave.forms(key)
        four = [forms[i % len(forms)] for i in range(4)]
        lines.append("    { { " + ", ".join(c_string(cave.stem(key, f)) for f in four) + " },")
        lines.append("      { " + ",\n        ".join(c_string(cave.english(key, f)) for f in four) + " },")
        lines.append(f"      {c_string(''.join(cave.names_in(key)))}, {c_string(cave.pronoun_persons(key))} }},")
    lines += ["};", ""]
    return "\n".join(lines)


