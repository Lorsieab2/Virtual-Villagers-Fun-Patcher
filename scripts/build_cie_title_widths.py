"""Write how wide each character of a title is in The Secret City, The Tree of Life and New Believers: their
island-event dialog draws the title on one line, centred, in ldwarialbold (src/vv_cie_graph.py title_px).  The
engine measures a title with placeholders once the names are filled in, and shows the names as pronouns when it does
not fit (docs/event-collection/cie-v6-binary.md 17).  From data/font_glyph_tables.json (src/vv_cie_graph.py reads
the same table), it writes

    native/vvfp_story_upgrades/story_title_widths.h

    python scripts/build_cie_title_widths.py
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
import vv_cie_graph as cg  # noqa: E402

OUT_H = ROOT / "native" / "vvfp_story_upgrades" / "story_title_widths.h"


def main() -> None:
    lines = ["/* GENERATED by scripts/build_cie_title_widths.py -- do not edit.  Each later game's title font",
             "   (ldwarialbold): the width of characters 32..126 (a character the font lacks measures as 'A'), the",
             "   spacing between two, and the title box (cie-v6-binary.md 5 and 17).  Index 0..2 = VV3..VV5. */", "",
             "static const unsigned char CG_TITLE_PX[3][95] = {"]
    for game in (3, 4, 5):
        widths = [cg.title_px(game, chr(c)) for c in range(32, 127)]
        if max(widths) > 255:
            raise SystemExit("a glyph wider than a byte")
        rows = [", ".join(str(w) for w in widths[i:i + 24]) for i in range(0, 95, 24)]
        lines.append("    { " + ",\n      ".join(rows) + " },")
    lines[-1] = lines[-1].rstrip(",")
    lines.append("};")
    spacing = [cg.title_px(g, "AA") - 2 * cg.title_px(g, "A") for g in (3, 4, 5)]
    lines.append(f"static const int CG_TITLE_SPACING[3] = {{ {', '.join(map(str, spacing))} }};")
    lines.append(f"static const int CG_TITLE_BOX_PX[3] = {{ {', '.join(str(cg.TITLE_BOX_PX[g]) for g in (3, 4, 5))} }};")
    lines.append("")
    OUT_H.write_bytes("\n".join(lines).encode())
    print(OUT_H)


if __name__ == "__main__":
    main()
