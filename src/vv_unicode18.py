"""Unicode 18.0 for the patcher: character properties, grapheme clusters and normalization.

The owner, 2026-11-02: "please extend support to the entire Unicode 18.0 chart collection" -- "to all games".
Python's own `unicodedata` is older than 18.0 (16.0 in Python 3.14), so it calls every character added since
unassigned ("Cn"), gives it no name, and cuts text by older rules.  Every check whose answer depends on the
Unicode version reads this module instead: the games' text rule (src/vv_game_text.py: what a name may hold,
whole-grapheme cuts and the byte limits), the translation validator, Picture Studio's Text tab and its
character search, and paste.

The tables are data/unicode18/ucd18.json.gz and names18.txt.gz, generated from the Unicode 18.0.0 Character
Database by scripts/build_unicode18_tables.py (sources and SHA-256s in data/unicode18/SOURCES.json; used under
the Unicode License v3, data/unicode18/LICENSE-Unicode.txt).  The in-game companions read the same facts from
native/vvfp_unicode_text/ucd18_tables.h, generated by the same script.

    category(ch)            the General_Category ("Lu", "Mn", "Cn"...)
    combining(ch)           the Canonical_Combining_Class
    bidirectional(ch)       the Bidi_Class
    east_asian_width(ch)    "W", "F", "Na", "H", "A" or "N"
    script(ch), block(ch)   the Script and Block names
    name(ch, default)       the character name (algorithmic names included)
    is_assigned(ch)         every code point UnicodeData 18.0 assigns
    normalize(form, text)   NFC, NFD, NFKC, NFKD by the 18.0 decompositions and exclusions
    graphemes(text)         extended grapheme clusters, UAX #29 as of 18.0 (GB3-GB13 with GB9c)
    emoji_sequences()       every sequence of emoji-sequences.txt and emoji-zwj-sequences.txt
"""
from __future__ import annotations

import bisect
import gzip
import json
from functools import lru_cache
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data" / "unicode18"
UNICODE_VERSION = "18.0.0"


class _Runs:
    """A property over 0..10FFFF as change points."""

    def __init__(self, runs) -> None:
        self.starts = [r[0] for r in runs]
        self.values = [r[1] for r in runs]

    def __call__(self, cp: int):
        return self.values[bisect.bisect_right(self.starts, cp) - 1]


class _Ranges:
    def __init__(self, ranges) -> None:
        self.firsts = [r[0] for r in ranges]
        self.lasts = [r[1] for r in ranges]

    def __contains__(self, cp: int) -> bool:
        i = bisect.bisect_right(self.firsts, cp) - 1
        return i >= 0 and cp <= self.lasts[i]


class _Tables:
    def __init__(self) -> None:
        t = json.loads(gzip.decompress((DATA / "ucd18.json.gz").read_bytes()).decode("utf-8"))
        if t["version"] != UNICODE_VERSION:
            raise ValueError(f"data/unicode18/ucd18.json.gz is Unicode {t['version']}, not {UNICODE_VERSION}")
        self.raw = t
        self.gc = _Runs(t["gc"])
        self.ccc = _Runs(t["ccc"])
        self.bidi = _Runs(t["bidi"])
        self.gcb = _Runs(t["gcb"])
        self.incb = _Runs(t["incb"])
        self.eaw = _Runs(t["eaw"])
        self.script_ix = _Runs(t["script"])
        self.scripts = t["scripts"]
        self.blocks = t["blocks"]
        self.block_starts = [b[0] for b in self.blocks]
        self.emoji = {k: _Ranges(v) for k, v in t["emoji"].items()}
        self.white = _Ranges(t["white_space"])
        self.ignorable = _Ranges(t["default_ignorable"])
        self.exclusions = _Ranges(t["composition_exclusions"])
        self.name_ranges = t["name_ranges"]
        self.canon: dict[int, tuple[int, ...]] = {}
        self.compat: dict[int, tuple[int, ...]] = {}
        for k, v in t["decomp"].items():
            cp = int(k, 16)
            parts = v.split()
            if parts[0].startswith("<"):
                self.compat[cp] = tuple(int(p, 16) for p in parts[1:])
            else:
                self.canon[cp] = tuple(int(p, 16) for p in parts)
        self.compose: dict[tuple[int, int], int] = {}
        for cp, d in self.canon.items():
            if len(d) == 2 and cp not in self.exclusions:
                self.compose[d] = cp


@lru_cache(maxsize=1)
def tables() -> _Tables:
    return _Tables()


def _cp(ch) -> int:
    return ch if isinstance(ch, int) else ord(ch)


# ---------------------------------------------------------------------------------------------- properties

def category(ch) -> str:
    return tables().gc(_cp(ch))


def combining(ch) -> int:
    return tables().ccc(_cp(ch))


def bidirectional(ch) -> str:
    return tables().bidi(_cp(ch))


def east_asian_width(ch) -> str:
    return tables().eaw(_cp(ch))


def script(ch) -> str:
    t = tables()
    return t.scripts[t.script_ix(_cp(ch))]


def block(ch) -> str:
    t = tables()
    cp = _cp(ch)
    i = bisect.bisect_right(t.block_starts, cp) - 1
    if i >= 0 and cp <= t.blocks[i][1]:
        return t.blocks[i][2]
    return "No_Block"


def blocks() -> list[tuple[int, int, str]]:
    return [tuple(b) for b in tables().blocks]


def is_assigned(ch) -> bool:
    return category(ch) != "Cn"


def is_white_space(ch) -> bool:
    return _cp(ch) in tables().white


def is_default_ignorable(ch) -> bool:
    return _cp(ch) in tables().ignorable


def has_property(ch, prop: str) -> bool:
    """An emoji-data.txt property: Emoji, Emoji_Presentation, Emoji_Modifier, Emoji_Modifier_Base,
    Emoji_Component, Extended_Pictographic."""
    r = tables().emoji.get(prop)
    return r is not None and _cp(ch) in r


def assigned_code_points():
    """Every code point UnicodeData 18.0 assigns (General_Category other than Cn), in order."""
    gc = tables().raw["gc"]
    for i, (start, value) in enumerate(gc):
        end = gc[i + 1][0] if i + 1 < len(gc) else 0x110000
        if value != "Cn":
            yield from range(start, end)


# ---------------------------------------------------------------------------------------------- names

_HANGUL_L = "G GG N D DD R M B BB S SS  J JJ C K T P H".split(" ")
_HANGUL_V = "A AE YA YAE EO E YEO YE O WA WAE OE YO U WEO WE WI YU EU YI I".split(" ")
_HANGUL_T = [""] + "G GG GS N NJ NH D L LG LM LB LS LT LP LH M B BS S SS NG J C K T P H".split(" ")


@lru_cache(maxsize=1)
def _names() -> dict[int, str]:
    out = {}
    for line in gzip.decompress((DATA / "names18.txt.gz").read_bytes()).decode("utf-8").splitlines():
        if line:
            k, v = line.split(";", 1)
            out[int(k, 16)] = v
    return out


def _range_name(cp: int) -> str | None:
    for first, last, label in tables().name_ranges:
        if first <= cp <= last:
            if label == "Hangul Syllable":
                s = cp - 0xAC00
                return ("HANGUL SYLLABLE " + _HANGUL_L[s // 588] + _HANGUL_V[(s % 588) // 28]
                        + _HANGUL_T[s % 28])
            if label.startswith("CJK Ideograph"):
                return f"CJK UNIFIED IDEOGRAPH-{cp:X}"
            if label.startswith("Tangut Ideograph"):
                return f"TANGUT IDEOGRAPH-{cp:X}"
            if label.startswith("Jurchen Character"):
                return f"JURCHEN CHARACTER-{cp:X}"
            if label.startswith("Seal Character"):
                return f"SEAL CHARACTER-{cp:X}"
            return None
    return None


def name(ch, default: str | None = None) -> str:
    cp = _cp(ch)
    n = _names().get(cp) or _range_name(cp)
    if n:
        return n
    if default is not None:
        return default
    raise ValueError("no such name")


def named_code_points():
    """Every code point that has a name, in order."""
    names = _names()
    ranges = [(a, b) for a, b, label in tables().name_ranges
              if label == "Hangul Syllable" or label.startswith(("CJK Ideograph", "Tangut Ideograph",
                                                                 "Jurchen Character", "Seal Character"))]
    points = set(names)
    for a, b in ranges:
        points.update(range(a, b + 1))
    return sorted(points)


# ---------------------------------------------------------------------------------------------- normalization

_SBASE, _LBASE, _VBASE, _TBASE = 0xAC00, 0x1100, 0x1161, 0x11A7
_LCOUNT, _VCOUNT, _TCOUNT = 19, 21, 28
_NCOUNT = _VCOUNT * _TCOUNT
_SCOUNT = _LCOUNT * _NCOUNT


def _decompose(cp: int, compat: bool, out: list[int]) -> None:
    t = tables()
    if _SBASE <= cp < _SBASE + _SCOUNT:
        s = cp - _SBASE
        out.append(_LBASE + s // _NCOUNT)
        out.append(_VBASE + (s % _NCOUNT) // _TCOUNT)
        if s % _TCOUNT:
            out.append(_TBASE + s % _TCOUNT)
        return
    d = t.canon.get(cp)
    if d is None and compat:
        d = t.compat.get(cp)
    if d is None:
        out.append(cp)
        return
    for c in d:
        _decompose(c, compat, out)


def _reorder(cps: list[int]) -> None:
    ccc = tables().ccc
    i = 0
    n = len(cps)
    while i < n:
        if ccc(cps[i]) == 0:
            i += 1
            continue
        j = i
        while j < n and ccc(cps[j]) != 0:
            j += 1
        cps[i:j] = sorted(cps[i:j], key=ccc)        # stable: equal classes keep their order
        i = j


def _pair(a: int, b: int) -> int | None:
    if _LBASE <= a < _LBASE + _LCOUNT and _VBASE <= b < _VBASE + _VCOUNT:
        return _SBASE + ((a - _LBASE) * _VCOUNT + (b - _VBASE)) * _TCOUNT
    if _SBASE <= a < _SBASE + _SCOUNT and (a - _SBASE) % _TCOUNT == 0 and _TBASE < b < _TBASE + _TCOUNT:
        return a + (b - _TBASE)
    return tables().compose.get((a, b))


def _compose(cps: list[int]) -> list[int]:
    """Canonical composition (UAX #15's algorithm)."""
    if not cps:
        return cps
    ccc = tables().ccc
    s = list(cps)
    starter = 0
    last = ccc(s[0])
    if last != 0:
        last = 256                      # text that starts with a mark: nothing composes onto it
    at = 1
    for i in range(1, len(s)):
        ch = s[i]
        c = ccc(ch)
        composite = _pair(s[starter], ch)
        if composite is not None and (last < c or last == 0):
            s[starter] = composite
            continue
        if c == 0:
            starter = at
        last = c
        s[at] = ch
        at += 1
    return s[:at]


def normalize(form: str, text: str) -> str:
    """`text` in normalization form NFC, NFD, NFKC or NFKD, by the Unicode 18.0 data."""
    if form not in ("NFC", "NFD", "NFKC", "NFKD"):
        raise ValueError(f"invalid normalization form {form!r}")
    if text.isascii():
        return text
    cps: list[int] = []
    for ch in text:
        _decompose(ord(ch), form in ("NFKC", "NFKD"), cps)
    _reorder(cps)
    if form in ("NFC", "NFKC"):
        cps = _compose(cps)
    return "".join(map(chr, cps))


# ---------------------------------------------------------------------------------------------- graphemes

(_OTHER, _CR, _LF, _CONTROL, _EXTEND, _ZWJ, _RI, _PREPEND, _SPACING, _L, _V, _T, _LV, _LVT) = range(14)
_INCB_LINKER, _INCB_CONSONANT, _INCB_EXTEND = 1, 2, 3


def grapheme_break_property(ch) -> int:
    return tables().gcb(_cp(ch))


def _breaks(cps: list[int]) -> list[bool]:
    """For each position i in 1..len-1, whether a grapheme boundary lies between cps[i-1] and cps[i]."""
    t = tables()
    gcb = t.gcb
    incb = t.incb
    extpict = t.emoji["Extended_Pictographic"]
    out = []
    prev = gcb(cps[0])
    ri = 1 if prev == _RI else 0
    emoji = 1 if cps[0] in extpict else 0          # 1: ExtPict Extend*, 2: ... ZWJ
    ib = incb(cps[0])
    conj = 1 if ib == _INCB_CONSONANT else 2 if ib == _INCB_LINKER else 0   # 2: a Linker [Extend Linker]*
    for cp in cps[1:]:
        p = gcb(cp)
        i = incb(cp)
        if prev == _CR and p == _LF:
            brk = False                                                 # GB3
        elif prev in (_CONTROL, _CR, _LF) or p in (_CONTROL, _CR, _LF):
            brk = True                                                  # GB4, GB5
        elif prev == _L and p in (_L, _V, _LV, _LVT):
            brk = False                                                 # GB6
        elif prev in (_LV, _V) and p in (_V, _T):
            brk = False                                                 # GB7
        elif prev in (_LVT, _T) and p == _T:
            brk = False                                                 # GB8
        elif p in (_EXTEND, _ZWJ):
            brk = False                                                 # GB9
        elif p == _SPACING:
            brk = False                                                 # GB9a
        elif prev == _PREPEND:
            brk = False                                                 # GB9b
        elif conj == 2 and i == _INCB_CONSONANT:
            brk = False                                                 # GB9c
        elif emoji == 2 and cp in extpict:
            brk = False                                                 # GB11
        elif prev == _RI and p == _RI and ri % 2 == 1:
            brk = False                                                 # GB12, GB13
        else:
            brk = True                                                  # GB999
        out.append(brk)
        # carry the states
        ri = ri + 1 if p == _RI else 0
        if cp in extpict:
            emoji = 1
        elif emoji == 1 and p == _EXTEND:
            emoji = 1
        elif emoji == 1 and p == _ZWJ:
            emoji = 2
        else:
            emoji = 0
        if i == _INCB_CONSONANT:
            conj = 1
        elif i == _INCB_LINKER:
            conj = 2                    # 18.0's GB9c: a linker joins the next consonant, after a consonant or not
        elif conj and i == _INCB_EXTEND:
            pass
        else:
            conj = 0
        prev = p
    return out


def graphemes(text: str) -> list[str]:
    """`text` cut into extended grapheme clusters by UAX #29 as of Unicode 18.0."""
    if not text:
        return []
    cps = [ord(c) for c in text]
    out = []
    start = 0
    for i, brk in enumerate(_breaks(cps), 1):
        if brk:
            out.append(text[start:i])
            start = i
    out.append(text[start:])
    return out


def grapheme_count(text: str) -> int:
    return len(graphemes(text))


# ---------------------------------------------------------------------------------------------- emoji

def emoji_sequences() -> list[tuple[str, str]]:
    """(type field, the sequence as text) for every line of emoji-sequences.txt and emoji-zwj-sequences.txt."""
    return [(kind, "".join(chr(int(c, 16)) for c in seq.split())) for kind, seq in tables().raw["emoji_sequences"]]


def grapheme_break_tests() -> list[tuple[list[int], list[bool]]]:
    """GraphemeBreakTest.txt 18.0: (code points, a boundary after each but the last)."""
    out = []
    for line in tables().raw["grapheme_break_tests"]:
        parts = line.split()
        cps = [int(p, 16) for p in parts[1::2]]
        marks = [m == "/" for m in parts[2:-1:2]]
        out.append((cps, marks))
    return out


def is_emoji(cluster: str) -> bool:
    """True when the cluster is shown as a colour emoji by Unicode's emoji presentation rules."""
    cps = [ord(c) for c in cluster]
    if not cps or 0xFE0E in cps:
        return False
    first = cps[0]
    if any(0x1F1E6 <= c <= 0x1F1FF for c in cps):
        return True
    if first in b"0123456789#*":
        return 0x20E3 in cps and 0xFE0F in cps
    if 0xFE0F in cps and has_property(first, "Emoji"):
        return True
    if has_property(first, "Emoji_Presentation"):
        return True
    if len(cps) > 1 and any(has_property(c, "Emoji_Modifier") for c in cps[1:]) and has_property(first, "Emoji"):
        return True
    if first == 0x1F3F4 and any(0xE0020 <= c <= 0xE007F for c in cps):
        return True
    return 0x200D in cps and sum(1 for c in cps if has_property(c, "Extended_Pictographic")) >= 2
