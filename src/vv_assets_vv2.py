def tile_name(x: int, y: int) -> str:
    """The island's tile (x, y): "Map" "X" x "Y" y ".jpg", made byte by byte at 0x41203C .. 0x4120BE."""
    return f"MapX{x}Y{y}.jpg"


def tile_files() -> list[str]:
    return [tile_name(x, y) for y in range(TILES_ACROSS) for x in range(TILES_ACROSS)]


def _hx(sites) -> str:
    return ", ".join(s if isinstance(s, str) else f"0x{s:X}" for s in sites)


def sheet_table() -> list[SheetSpec]:
    """Every sprite the stock executable builds, once per (file, cut), with its constructor calls in `where`."""
    merged: dict[tuple, dict] = {}

    def add(name, cols, rows, sheets=(1, 1), whole=False, where=""):
        key = (name.casefold(), cols, rows, tuple(sheets))
        e = merged.setdefault(key, {"name": name, "cols": cols, "rows": rows, "sheets": tuple(sheets),
                                    "whole": whole, "where": []})
        e["whole"] = e["whole"] or whole
        e["where"].append(where)
    for name, cols, rows, sites in ONE_SHEETS:
        add(name, cols, rows, where=f"0x40A270 at {_hx(sites)}")
    for name, sites in WHOLE_PICTURES:
        add(name, 1, 1, whole=True, where=f"0x40A0D0 at {_hx(sites)}")
    for name in tile_files():
        add(name, 1, 1, whole=True, where=f"0x40A0D0 at 0x{TILE_SITE:X} (the island's tiles, 0x411FF0)")
    for prefix, sheets, cols, rows, site in GRIDS:
        add(prefix, cols, rows, sheets, where=f"0x40A2F0 at 0x{site:X}")
    for name, sites in BUTTONS:
        add(name, 3, 1, where=f"a button: 0x4019D0 at {_hx(sites)}, its sheet 0x40A270 at 0x{BUTTON_SHEET_SITE:X}")
    for name, site, _table in FONTS_BUILT:
        add(name, 1, 1, whole=True, where=f"a font: 0x402110 at 0x{site:X}, loaded whole at 0x4025A9")
    out = []
    for e in merged.values():
        note = NEVER_DRAWN.get(e["name"])
        where = "; ".join(e["where"]) + (f" (built, never drawn: {note})" if note else "")
        out.append(SheetSpec(e["name"], e["cols"], e["rows"], e["sheets"], whole=e["whole"], used=note is None,
                             where=where))
    return out


def grids() -> dict[str, tuple[int, int]]:
    """file (case folded) -> (cols, rows) of the one sprite the game cuts it into (one sheet only)."""
    out = {}
    for spec in sheet_table():
        if tuple(spec.sheets) == (1, 1):
            out[spec.name.casefold()] = (spec.cols, spec.rows)
    return out


