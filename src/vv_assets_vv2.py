# ------------------------------------------------------------------ plans from the sheets' sizes

def _atlas(name: str) -> pi.Atlas:
    cols, rows = grids().get(name.casefold(), (1, 1))
    return pi.Atlas(name, cols, rows)


def plan_of(sheets, entries) -> tuple:
    """Blits of GENERATED entries (file, col, row, x, y, scale, alpha), each cell cut as the game cuts it."""
    out = []
    for name, col, row, x, y, scale, alpha in entries:
        out.append(pa.cell_plan(sheets, _atlas(name), col, row, x, y, scale, alpha))
    return tuple(out)


def _files_of(entries) -> set:
    return {e[0] for e in entries}


def _has(sheets, names) -> bool:
    return all(sheets.has(n) for n in names)


def _cells(sheets, name: str, cols: int, rows: int, labels=None) -> tuple:
    """Every cell of a sprite as its constructor cuts it, in the game's frame order (across, then down)."""
    at = pi.Atlas(name, cols, rows)
    frames = []
    for row in range(rows):
        for col in range(cols):
            k = row * cols + col
            label = labels[k] if labels is not None else f"frame {k}"
            frames.append(Frame(label, (pa.cell_plan(sheets, at, col, row),)))
    return tuple(frames)


def _whole(sheets, key, category, label, name, **kw) -> Asset | None:
    return pa.one(sheets, key, category, label, name, **kw) if sheets.has(name) else None


def generated_assets(sheets) -> list[Asset]:
    out = []
    for key, category, group, label, note, proof, rows in GENERATED:
        frames = []
        for flabel, entries, _state, _span in rows:
            if entries and _has(sheets, _files_of(entries)):
                frames.append(Frame(flabel, plan_of(sheets, entries)))
        if frames:
            out.append(Asset(key, category, label, tuple(frames), group=group, note=note, proof=proof))
    return out


