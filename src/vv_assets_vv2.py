def unused_assets(sheets) -> list[Asset]:
    """Pictures the stock executable never loads, and sprites it builds but never draws."""
    covered = set()
    for spec in sheet_table():
        covered.update(n.casefold() for n in spec.files())
    out = []
    for name in sheets.names():
        if name.casefold() in covered or not name.casefold().endswith(pa.PICTURE_EXTENSIONS):
            continue
        if name.casefold() == MASK_FILE:
            continue                      # the Origins patch's own atlas, extracted into Images by its DLL
        out.append(Asset(f"unused:{name}", UNUSED, name, (Frame("", (pa.whole_plan(sheets, name),)),),
                         group="Never loaded by the game", unused=True,
                         note="the executable never names it; " + NOT_PLACED + " (its cells: Source sheets)",
                         proof="exe scan"))
    for name, why in NEVER_DRAWN.items():
        if sheets.has(name):
            out.append(Asset(f"unused:{name}", UNUSED, name, (Frame("", (pa.whole_plan(sheets, name),)),),
                             group="Built, never drawn", unused=True, note=f"built at load; {why}; " + NOT_PLACED,
                             proof="exe scan"))
    return out


