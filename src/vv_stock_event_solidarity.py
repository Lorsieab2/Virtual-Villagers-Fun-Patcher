"""Village Solidarity and the games' OWN island events (the owner, 2026-11-20, v1.35.97): one tag per result.

The one source is data/stock_island_event_solidarity.txt (its header says the columns).  This module reads it and
renders native/vvfp_island_events/stock_solidarity_table.inc, the table "VVFP Island Events.dll" carries
(scripts/build_stock_solidarity_table.py writes it; tests/test_stock_event_solidarity.py keeps the two the same).
"""
from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data" / "stock_island_event_solidarity.txt"
TABLE_INC = ROOT / "native" / "vvfp_island_events" / "stock_solidarity_table.inc"

TAGS = {"RAISE": 1, "LOWER": 2, "NEUTRAL": 3}          # the Village Solidarity companion's tag codes
WHENS = ("-", "food+", "food-", "tech+", "tech-", "lost", "joined", "sick", "sick2", "hurt", "healed", "weather")


@dataclass(frozen=True)
class Row:
    game: int
    title: str
    answer: str            # "" for an event with no choice
    when: str              # "" always
    tag: str               # RAISE / LOWER / NEUTRAL
    result: str


def parse(text: str | None = None) -> list[Row]:
    """Every row of the table, in its order; a malformed row raises ValueError naming its line."""
    if text is None:
        text = DATA.read_text(encoding="utf-8")
    rows: list[Row] = []
    for number, line in enumerate(text.splitlines(), 1):
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        cells = [c.strip() for c in line.split(" | ")]
        if len(cells) != 6:
            raise ValueError(f"line {number}: six columns are needed, not {len(cells)}: {line!r}")
        game, title, answer, when, tag, result = cells
        if game not in ("VV1", "VV2", "VV3", "VV4", "VV5"):
            raise ValueError(f"line {number}: unknown game {game!r}")
        if tag not in TAGS:
            raise ValueError(f"line {number}: the tag must be RAISE, LOWER or NEUTRAL, not {tag!r}")
        if when not in WHENS:
            raise ValueError(f"line {number}: unknown WHEN {when!r}")
        if not title or title == "-":
            raise ValueError(f"line {number}: no title")
        for cell in (title, answer, when):
            if any(ord(ch) > 0x7E for ch in cell) or "\\" in cell:
                raise ValueError(f"line {number}: plain ASCII only: {cell!r}")
        rows.append(Row(int(game[2]), title, "" if answer == "-" else answer, "" if when == "-" else when, tag,
                        result))
    return rows


def tag_of(rows: list[Row], game: int, title: str, answer: str, facts: set[str]) -> str | None:
    """The tag of the result shown -- the same rule the companion runs (stock_solidarity.inc): the first row of
    `game`, `title` and `answer` (spaces collapsed, a final "." dropped) whose WHEN holds; None when none does."""
    def words(s: str) -> str:
        return " ".join(s.split()).rstrip(" .")
    for row in rows:
        if row.game != game or words(row.title) != words(title) or words(row.answer) != words(answer):
            continue
        if not row.when or row.when in facts:
            return row.tag
    return None


def _c(s: str) -> str:
    return '"' + s.replace('"', '\\"') + '"'


def render_c(rows: list[Row] | None = None) -> str:
    rows = parse() if rows is None else rows
    lines = [
        "/* GENERATED by scripts/build_stock_solidarity_table.py from data/stock_island_event_solidarity.txt -- do not",
        "   edit: change the data file and run the script (tests/test_stock_event_solidarity.py checks they agree).",
        "   game, title, answer (\"\" none), when (\"\" always), tag (1 raise, 2 lower, 3 neutral). */",
        "static const struct stock_tag STOCK_TAGS[] = {",
    ]
    for r in rows:
        lines.append(f"    {{ {r.game}, {_c(r.title)}, {_c(r.answer)}, {_c(r.when)}, {TAGS[r.tag]} }},")
    lines.append("};")
    lines.append("")
    return "\n".join(lines)


def counts(rows: list[Row] | None = None) -> dict[int, dict[str, int]]:
    rows = parse() if rows is None else rows
    out: dict[int, dict[str, int]] = {g: {t: 0 for t in TAGS} for g in range(1, 6)}
    for r in rows:
        out[r.game][r.tag] += 1
    return out
